begin;

update public.commodities
set available_quantity = 0
where available_quantity is null;

update public.commodities
set commodity_status = case
  when available_quantity <= 0
    and lower(coalesce(commodity_status, 'available')) = 'available'
    then 'out_of_stock'
  when available_quantity > 0
    and lower(coalesce(commodity_status, 'available')) = 'out_of_stock'
    then 'available'
  else lower(coalesce(commodity_status, 'available'))
end;

alter table public.commodities
  alter column available_quantity set default 0,
  alter column available_quantity set not null;

alter table public.commodities
  drop constraint if exists commodities_available_quantity_nonnegative;
alter table public.commodities
  add constraint commodities_available_quantity_nonnegative
  check (available_quantity >= 0);

create or replace function private.sync_commodity_stock_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.available_quantity <= 0
     and lower(coalesce(new.commodity_status, 'available')) = 'available' then
    new.commodity_status := 'out_of_stock';
  elsif new.available_quantity > 0
     and lower(coalesce(new.commodity_status, 'available')) = 'out_of_stock' then
    new.commodity_status := 'available';
  end if;
  return new;
end;
$$;

drop trigger if exists commodities_sync_stock_status on public.commodities;
create trigger commodities_sync_stock_status
before insert or update of available_quantity, commodity_status
on public.commodities
for each row execute function private.sync_commodity_stock_status();

create table if not exists private.commodity_restock_history (
  restock_id bigint generated by default as identity primary key,
  commodity_id bigint not null
    references public.commodities (commodity_id) on delete restrict,
  quantity_added numeric(14,3) not null check (quantity_added > 0),
  previous_quantity numeric(14,3) not null check (previous_quantity >= 0),
  new_quantity numeric(14,3) not null check (new_quantity >= 0),
  performed_by uuid not null references auth.users (id) on delete restrict,
  reason text,
  created_at timestamptz not null default now(),
  constraint commodity_restock_history_quantity_check
    check (new_quantity = previous_quantity + quantity_added),
  constraint commodity_restock_history_reason_length_check
    check (reason is null or length(reason) <= 240)
);

create index if not exists commodity_restock_history_commodity_created_idx
  on private.commodity_restock_history (commodity_id, created_at desc);

alter table private.commodity_restock_history enable row level security;
revoke all on private.commodity_restock_history
  from public, anon, authenticated;

create or replace function public.restock_current_farmer_commodity(
  p_commodity_id bigint,
  p_quantity numeric,
  p_reason text default null
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  commodity_record public.commodities%rowtype;
  previous_quantity numeric(14,3);
  resulting_quantity numeric(14,3);
  normalized_reason text := nullif(btrim(coalesce(p_reason, '')), '');
begin
  if (select auth.uid()) is null then
    raise exception 'An authenticated farmer account is required'
      using errcode = '42501';
  end if;
  if p_commodity_id is null or p_commodity_id <= 0 then
    raise exception 'Select a valid product to restock'
      using errcode = '22023';
  end if;
  if p_quantity is null or p_quantity <= 0 then
    raise exception 'Restock quantity must be greater than zero'
      using errcode = '22023';
  end if;
  if p_quantity > 1000000 or scale(p_quantity) > 3 then
    raise exception 'Restock quantity must be at most 1,000,000 with up to 3 decimal places'
      using errcode = '22023';
  end if;
  if normalized_reason is not null and length(normalized_reason) > 240 then
    raise exception 'Restock notes must be 240 characters or fewer'
      using errcode = '22023';
  end if;

  select commodity.* into commodity_record
  from public.commodities as commodity
  where commodity.commodity_id = p_commodity_id
  for update;

  if not found then
    raise exception 'The selected product no longer exists'
      using errcode = '22023';
  end if;
  if not private.owns_farm(commodity_record.farm_id)
     and not private.is_admin() then
    raise exception 'You are not authorized to restock this product'
      using errcode = '42501';
  end if;
  if lower(coalesce(commodity_record.commodity_status, 'available')) = 'sold' then
    raise exception 'Mark this product as unsold before adding stock'
      using errcode = '22023';
  end if;

  previous_quantity := commodity_record.available_quantity;
  resulting_quantity := previous_quantity + p_quantity;
  if resulting_quantity > 1000000 then
    raise exception 'Resulting stock cannot exceed 1,000,000'
      using errcode = '22023';
  end if;

  update public.commodities
  set available_quantity = resulting_quantity,
      updated_at = now()
  where commodity_id = p_commodity_id;

  insert into private.commodity_restock_history (
    commodity_id, quantity_added, previous_quantity, new_quantity,
    performed_by, reason
  ) values (
    p_commodity_id, p_quantity, previous_quantity, resulting_quantity,
    (select auth.uid()), normalized_reason
  );

  return jsonb_build_object(
    'commodity_id', p_commodity_id,
    'previous_quantity', previous_quantity,
    'quantity_added', p_quantity,
    'new_quantity', resulting_quantity,
    'commodity_status', 'available'
  );
end;
$$;

revoke all on function private.sync_commodity_stock_status()
  from public, anon, authenticated;
revoke all on function public.restock_current_farmer_commodity(bigint, numeric, text)
  from public, anon;
grant execute on function public.restock_current_farmer_commodity(bigint, numeric, text)
  to authenticated;

revoke update (available_quantity) on public.commodities from authenticated;

notify pgrst, 'reload schema';
commit;
