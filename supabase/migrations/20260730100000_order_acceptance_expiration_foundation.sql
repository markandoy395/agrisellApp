begin;

alter table public.orders
  add column if not exists acceptance_expires_at timestamptz,
  add column if not exists acceptance_halfway_at timestamptz,
  add column if not exists acceptance_expired_at timestamptz,
  add column if not exists acceptance_halfway_reminder_sent_at timestamptz,
  add column if not exists acceptance_reminder_sent_at timestamptz;

create table if not exists private.order_acceptance_events (
  event_id bigint generated by default as identity primary key,
  seller_order_id text not null references private.seller_order_registry (
    seller_order_id
  ),
  event_type text not null check (event_type in (
    'halfway_reminder', 'deadline_reminder', 'expired',
    'expired_payment_reviewed', 'refunded'
  )),
  occurred_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  unique (seller_order_id, event_type)
);

alter table private.order_acceptance_events enable row level security;
revoke all on private.order_acceptance_events
  from public, anon, authenticated;

create or replace function private.order_acceptance_time(
  source_time timestamptz,
  active_duration interval
) returns timestamptz language plpgsql stable set search_path = '' as $$
declare
  local_start timestamp := timezone(
    'Asia/Manila', coalesce(source_time, now())
  );
  local_close timestamp;
  local_deadline timestamp;
  overflow interval;
begin
  if local_start::time < time '06:00' then
    local_start := local_start::date + time '06:00';
  elsif local_start::time >= time '20:00' then
    local_start := (local_start::date + 1) + time '06:00';
  end if;

  local_close := local_start::date + time '20:00';
  local_deadline := local_start + active_duration;
  if local_deadline > local_close then
    overflow := local_deadline - local_close;
    local_deadline := (local_start::date + 1) + time '06:00' + overflow;
  end if;
  return local_deadline at time zone 'Asia/Manila';
end;
$$;

create or replace function private.order_acceptance_deadline(
  source_time timestamptz
) returns timestamptz language sql stable set search_path = '' as $$
  select private.order_acceptance_time(source_time, interval '4 hours')
$$;

create or replace function private.order_acceptance_halfway(
  source_time timestamptz
) returns timestamptz language sql stable set search_path = '' as $$
  select private.order_acceptance_time(source_time, interval '2 hours')
$$;

create or replace function private.set_order_acceptance_deadline()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.order_status = 'toShip' and new.acceptance_expires_at is null then
    new.acceptance_expires_at := private.order_acceptance_deadline(
      coalesce(new.order_date, new.created_at, now())
    );
    new.acceptance_halfway_at := private.order_acceptance_halfway(
      coalesce(new.order_date, new.created_at, now())
    );
  end if;
  return new;
end;
$$;

drop trigger if exists orders_set_acceptance_deadline on public.orders;
create trigger orders_set_acceptance_deadline
before insert on public.orders for each row
execute function private.set_order_acceptance_deadline();

update public.orders as order_record
set acceptance_expires_at = case
  when order_record.order_status = 'toShip'
    then private.order_acceptance_deadline(now())
  else private.order_acceptance_deadline(
    coalesce(order_record.order_date, order_record.created_at, now())
  )
end,
acceptance_halfway_at = case
  when order_record.order_status = 'toShip'
    then private.order_acceptance_halfway(now())
  else private.order_acceptance_halfway(
    coalesce(order_record.order_date, order_record.created_at, now())
  )
end
where order_record.acceptance_expires_at is null;

alter table public.orders
  drop constraint if exists orders_acceptance_expiry_check;
alter table public.orders
  add constraint orders_acceptance_expiry_check check (
    acceptance_expired_at is null or acceptance_expires_at is not null
  );

create index if not exists orders_pending_acceptance_expiry_idx
  on public.orders (acceptance_expires_at)
  where order_status = 'toShip' and acceptance_expired_at is null;

create or replace function private.guard_expired_order_acceptance()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.order_status = 'preparing' and (
    old.order_status <> 'toShip'
    or old.acceptance_expired_at is not null
    or old.acceptance_expires_at <= now()
  ) then
    raise exception 'This order can no longer be accepted'
      using errcode = '22023';
  end if;
  return new;
end;
$$;

drop trigger if exists orders_guard_expired_acceptance on public.orders;
create trigger orders_guard_expired_acceptance
before update of order_status on public.orders for each row
execute function private.guard_expired_order_acceptance();

drop trigger if exists orders_notify_status_after_update on public.orders;
create trigger orders_notify_status_after_update
after update of order_status on public.orders for each row
when (
  new.order_status is distinct from old.order_status
  and new.order_status <> 'expired'
)
execute function private.notify_order_status_change();

revoke all on function private.order_acceptance_time(timestamptz, interval),
  private.order_acceptance_deadline(timestamptz),
  private.order_acceptance_halfway(timestamptz),
  private.set_order_acceptance_deadline(),
  private.guard_expired_order_acceptance()
  from public, anon, authenticated;

commit;
