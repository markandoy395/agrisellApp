-- Persist review moderation state and its append-only administrative history.
begin;

create table if not exists public.admin_review_moderation (
  review_type text not null check (review_type in ('farmer', 'rider')),
  review_id text not null,
  visibility_status text not null default 'published'
    check (visibility_status in ('published', 'hidden')),
  report_status text not null default 'none'
    check (report_status in ('none', 'open', 'resolved', 'dismissed')),
  abuse_flags text[] not null default '{}',
  last_note text,
  updated_by_email text not null,
  updated_at timestamptz not null default now(),
  primary key (review_type, review_id),
  check (abuse_flags <@ array[
    'spam', 'harassment', 'hate_speech', 'profanity', 'scam',
    'personal_information', 'other'
  ]::text[]),
  check (last_note is null or char_length(last_note) <= 500)
);

create table if not exists public.admin_review_moderation_events (
  event_id bigint generated by default as identity primary key,
  review_type text not null check (review_type in ('farmer', 'rider')),
  review_id text not null,
  action text not null check (action in (
    'hidden', 'published', 'report_resolved', 'report_dismissed',
    'report_reopened', 'abuse_flag_added', 'abuse_flag_removed'
  )),
  abuse_flag text,
  note text,
  created_by_email text not null,
  created_at timestamptz not null default now(),
  check (note is null or char_length(note) <= 500)
);

create index if not exists admin_review_moderation_events_review_created_idx
  on public.admin_review_moderation_events
  (review_type, review_id, created_at desc, event_id desc);

alter table public.admin_review_moderation enable row level security;
alter table public.admin_review_moderation_events enable row level security;
revoke all on public.admin_review_moderation from public, anon, authenticated;
revoke all on public.admin_review_moderation_events from public, anon, authenticated;

create or replace function public.admin_moderate_review(
  p_review_type text,
  p_review_id text,
  p_action text,
  p_actor_email text,
  p_abuse_flag text default null,
  p_note text default null
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  allowed_flags constant text[] := array[
    'spam', 'harassment', 'hate_speech', 'profanity', 'scam',
    'personal_information', 'other'
  ];
  saved public.admin_review_moderation%rowtype;
  saved_event public.admin_review_moderation_events%rowtype;
  normalized_note text := nullif(btrim(p_note), '');
begin
  if p_review_type not in ('farmer', 'rider') or nullif(btrim(p_review_id), '') is null then
    raise exception 'A valid review is required' using errcode = '22023';
  end if;
  if p_action not in (
    'hide', 'publish', 'resolve_report', 'dismiss_report', 'reopen_report',
    'add_abuse_flag', 'remove_abuse_flag'
  ) then
    raise exception 'A valid moderation action is required' using errcode = '22023';
  end if;
  if char_length(coalesce(normalized_note, '')) > 500 then
    raise exception 'Moderation notes must be at most 500 characters' using errcode = '22023';
  end if;
  if p_action in ('add_abuse_flag', 'remove_abuse_flag')
     and not (p_abuse_flag = any(allowed_flags)) then
    raise exception 'A valid abuse flag is required' using errcode = '22023';
  end if;
  if p_review_type = 'farmer' and not exists (
    select 1 from public.reviews where review_id::text = p_review_id
  ) then
    raise exception 'Review not found' using errcode = 'P0002';
  elsif p_review_type = 'rider' and not exists (
    select 1 from public.rider_ratings where rating_id::text = p_review_id
  ) then
    raise exception 'Review not found' using errcode = 'P0002';
  end if;

  insert into public.admin_review_moderation (
    review_type, review_id, updated_by_email
  ) values (p_review_type, p_review_id, p_actor_email)
  on conflict (review_type, review_id) do nothing;

  update public.admin_review_moderation
  set visibility_status = case p_action
        when 'hide' then 'hidden'
        when 'publish' then 'published'
        else visibility_status
      end,
      report_status = case p_action
        when 'resolve_report' then 'resolved'
        when 'dismiss_report' then 'dismissed'
        when 'reopen_report' then 'open'
        else report_status
      end,
      abuse_flags = case p_action
        when 'add_abuse_flag' then array(
          select distinct flag from unnest(abuse_flags || p_abuse_flag) as flag order by flag
        )
        when 'remove_abuse_flag' then array_remove(abuse_flags, p_abuse_flag)
        else abuse_flags
      end,
      last_note = normalized_note,
      updated_by_email = p_actor_email,
      updated_at = now()
  where review_type = p_review_type and review_id = p_review_id
  returning * into saved;

  insert into public.admin_review_moderation_events (
    review_type, review_id, action, abuse_flag, note, created_by_email
  ) values (
    p_review_type,
    p_review_id,
    case p_action
      when 'hide' then 'hidden'
      when 'publish' then 'published'
      when 'resolve_report' then 'report_resolved'
      when 'dismiss_report' then 'report_dismissed'
      when 'reopen_report' then 'report_reopened'
      when 'add_abuse_flag' then 'abuse_flag_added'
      else 'abuse_flag_removed'
    end,
    case when p_action in ('add_abuse_flag', 'remove_abuse_flag') then p_abuse_flag end,
    normalized_note,
    p_actor_email
  ) returning * into saved_event;

  return jsonb_build_object('moderation', to_jsonb(saved), 'event', to_jsonb(saved_event));
end;
$$;

revoke all on function public.admin_moderate_review(text, text, text, text, text, text)
  from public, anon, authenticated;
grant execute on function public.admin_moderate_review(text, text, text, text, text, text)
  to service_role;

-- Keep hidden reviews out of the marketplace and expose only the newest public
-- administrator reply. Direct messages are intentionally excluded.
create or replace function public.marketplace_product_reviews(
  target_commodity_id bigint
) returns jsonb language sql stable security definer set search_path = '' as $$
  with visible_reviews as (
    select review.review_id, review.rating, coalesce(review.comment, '') as comment,
      review.created_at, public_response.message as admin_response,
      public_response.created_at as admin_responded_at,
      moderation.last_note as moderation_note,
      case when moderation.report_status in ('open', 'resolved', 'dismissed')
        then moderation.report_status else null end as moderation_status,
      coalesce(
        nullif(btrim(concat_ws(' ', app_user.first_name,
          left(coalesce(app_user.last_name, ''), 1) ||
          case when app_user.last_name is null then '' else '.' end)), ''),
        'Verified buyer'
      ) as reviewer_name
    from public.reviews as review
    join public.orders as order_record on order_record.order_id = review.order_id
    join public.cart_items as cart_item
      on cart_item.cart_item_id = order_record.cart_item_id
    join public.carts as cart on cart.cart_id = cart_item.cart_id
    join public.buyers as buyer on buyer.buyer_user_id = cart.buyer_user_id
    join public.users as app_user on app_user.user_id = buyer.user_id
    left join public.admin_review_moderation as moderation
      on moderation.review_type = 'farmer'
     and moderation.review_id = review.review_id::text
    left join lateral (
      select response.message, response.created_at
      from public.admin_review_responses as response
      where response.review_type = 'farmer'
        and response.review_id = review.review_id::text
        and response.response_mode = 'public'
      order by response.created_at desc, response.response_id desc
      limit 1
    ) as public_response on true
    where cart_item.commodity_id = target_commodity_id
      and order_record.order_status = 'delivered'
      and coalesce(moderation.visibility_status, 'published') = 'published'
      and (select auth.uid()) is not null
  )
  select jsonb_build_object(
    'averageRating', coalesce(round(avg(rating), 2), 0),
    'reviewCount', count(*),
    'reviews', coalesce(jsonb_agg(jsonb_strip_nulls(jsonb_build_object(
      'reviewerName', reviewer_name, 'rating', rating, 'comment', comment,
      'submittedAt', created_at, 'adminResponse', admin_response,
      'adminRespondedAt', admin_responded_at,
      'moderationNote', moderation_note,
      'moderationStatus', moderation_status
    )) order by created_at desc), '[]'::jsonb)
  ) from visible_reviews
$$;

revoke all on function public.marketplace_product_reviews(bigint) from public, anon;
grant execute on function public.marketplace_product_reviews(bigint) to authenticated;

notify pgrst, 'reload schema';

commit;
