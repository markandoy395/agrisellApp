begin;

create table public.admin_workspace_preferences (
  admin_email text primary key,
  auto_approve_verified_listings boolean not null default true,
  daily_admin_digest boolean not null default true,
  updated_at timestamptz not null default now()
);

create table public.admin_manual_records (
  record_id bigint generated by default as identity primary key,
  section text not null check (section in ('Logistics Companies')),
  name text not null check (char_length(btrim(name)) between 1 and 200),
  created_by_email text not null,
  created_at timestamptz not null default now()
);
create index admin_manual_records_section_created_idx
  on public.admin_manual_records (section, created_at desc);

create table public.admin_review_responses (
  response_id bigint generated by default as identity primary key,
  review_type text not null check (review_type in ('farmer', 'rider')),
  review_id text not null,
  response_mode text not null check (response_mode in ('public', 'direct')),
  message text not null check (char_length(btrim(message)) between 1 and 1000),
  created_by_email text not null,
  created_at timestamptz not null default now()
);
create index admin_review_responses_review_created_idx
  on public.admin_review_responses (review_type, review_id, created_at desc);

create table public.admin_farmer_information_requests (
  request_id bigint generated by default as identity primary key,
  farmer_user_id bigint not null references public.farmers (farmer_user_id) on delete cascade,
  requested_by_email text not null,
  status text not null default 'pending' check (status in ('pending', 'completed', 'cancelled')),
  created_at timestamptz not null default now()
);
create index admin_farmer_information_requests_farmer_created_idx
  on public.admin_farmer_information_requests (farmer_user_id, created_at desc);

alter table public.admin_workspace_preferences enable row level security;
alter table public.admin_manual_records enable row level security;
alter table public.admin_review_responses enable row level security;
alter table public.admin_farmer_information_requests enable row level security;

revoke all on public.admin_workspace_preferences from public, anon, authenticated;
revoke all on public.admin_manual_records from public, anon, authenticated;
revoke all on public.admin_review_responses from public, anon, authenticated;
revoke all on public.admin_farmer_information_requests from public, anon, authenticated;

create policy admin_review_responses_public_read
  on public.admin_review_responses for select to authenticated
  using (response_mode = 'public');
grant select (
  response_id, review_type, review_id, response_mode, message, created_at
) on public.admin_review_responses to authenticated;

commit;
