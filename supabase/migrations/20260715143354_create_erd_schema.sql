begin;

create table public.users (
  user_id bigint generated by default as identity primary key,
  first_name text, middle_name text, last_name text, extension_name text,
  email text, contact_number text, password_hash text, profile_photo_url text,
  account_status text, created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(), gender text,
  date_of_birth date, e_wallet_details jsonb
);

create table public.admins (
  user_id bigint primary key,
  admin_role text, admin_code text, date_assigned timestamptz,
  assigned_by_user_id bigint, created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint admins_users_fk foreign key (user_id)
    references public.users (user_id) on update restrict on delete restrict
);

create table public.admin_roles (
  admin_role_id bigint generated by default as identity,
  user_id bigint not null, role_name text, description text, role_level integer,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  constraint admin_roles_pkey primary key (admin_role_id, user_id),
  constraint admin_roles_admins_fk foreign key (user_id)
    references public.admins (user_id) on update restrict on delete restrict
);

create table public.buyers (
  buyer_user_id bigint generated by default as identity primary key,
  user_id bigint not null, shipping_address text, loyalty_points integer,
  preferred_payment_method text, gps_lat numeric(10,7), gps_long numeric(10,7),
  user_type text, business_name text,
  constraint buyers_users_fk foreign key (user_id)
    references public.users (user_id) on update restrict on delete restrict
);

create table public.farmers (
  farmer_user_id bigint generated by default as identity primary key,
  years_of_experience integer, bank_details jsonb, certification text,
  registration_date date
);

create table public.farms (
  farm_id bigint generated by default as identity primary key,
  farmer_user_id bigint not null, farm_name text, farm_location text,
  gps_lat numeric(10,7), gps_long numeric(10,7), total_crops integer,
  farm_size_hectares numeric(12,3), farming_type text,
  created_at timestamptz not null default now(), soil_type text,
  irrigation_type text, main_crops text[], certifications text[], farm_images text[],
  constraint farms_farmers_fk foreign key (farmer_user_id)
    references public.farmers (farmer_user_id) on update restrict on delete restrict
);

create table public.categories (
  category_id bigint generated by default as identity,
  category_name text, description text, status text,
  created_at timestamptz not null default now(), farm_id bigint not null,
  constraint categories_pkey primary key (category_id, farm_id),
  constraint categories_farms_fk foreign key (farm_id)
    references public.farms (farm_id) on update restrict on delete restrict
);

create table public.commodities (
  commodity_id bigint generated by default as identity primary key,
  category_id bigint not null, commodity_name text, description text,
  price_per_unit numeric(14,2), unit_type text, available_quantity numeric(14,3),
  harvest_date date, production_status text, is_organic boolean, image_url text,
  commodity_status text, created_at timestamptz not null default now(),
  minimum_order_quantity numeric(14,3), grade_quality text,
  updated_at timestamptz not null default now(), farm_id bigint not null,
  constraint commodities_categories_fk foreign key (category_id, farm_id)
    references public.categories (category_id, farm_id) on update restrict on delete restrict
);

create table public.carts (
  cart_id bigint generated by default as identity primary key,
  buyer_user_id bigint not null, cart_status text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  constraint carts_buyers_fk foreign key (buyer_user_id)
    references public.buyers (buyer_user_id) on update restrict on delete restrict
);

create table public.cart_items (
  cart_item_id bigint generated by default as identity primary key,
  cart_id bigint not null, commodity_id bigint not null, quantity numeric(14,3),
  price_at_time numeric(14,2), created_at timestamptz not null default now(),
  constraint cart_items_carts_fk foreign key (cart_id)
    references public.carts (cart_id) on update restrict on delete restrict,
  constraint cart_items_commodities_fk foreign key (commodity_id)
    references public.commodities (commodity_id) on update restrict on delete restrict
);

create table public.orders (
  order_id bigint generated by default as identity primary key,
  cart_item_id bigint not null, order_date timestamptz, order_status text,
  total_amount numeric(14,2), payment_status text, delivery_address text,
  payment_method text, created_at timestamptz not null default now(), delivery_date date,
  constraint orders_cart_items_fk foreign key (cart_item_id)
    references public.cart_items (cart_item_id) on update restrict on delete restrict
);

create table public.order_items (
  order_item_id bigint generated by default as identity primary key,
  order_id bigint not null, quantity numeric(14,3), unit_price numeric(14,2),
  total_price numeric(14,2),
  constraint order_items_orders_fk foreign key (order_id)
    references public.orders (order_id) on update restrict on delete restrict
);

create table public.reviews (
  review_id bigint generated by default as identity primary key,
  order_id bigint not null, rating numeric(3,2), comment text,
  created_at timestamptz not null default now(),
  constraint reviews_orders_fk foreign key (order_id)
    references public.orders (order_id) on update restrict on delete restrict
);

create table public.payments (
  payment_id bigint generated by default as identity primary key,
  order_id bigint not null, amount numeric(14,2), payment_method text,
  transaction_reference text, payment_date timestamptz, payment_status text,
  created_at timestamptz not null default now(),
  constraint payments_orders_fk foreign key (order_id)
    references public.orders (order_id) on update restrict on delete restrict
);

create table public.deliveries (
  delivery_id bigint generated by default as identity primary key,
  order_id bigint not null, delivery_status text, estimated_delivery_time timestamptz,
  actual_delivery_time timestamptz, created_at timestamptz not null default now(),
  vehicle_types text, cold_chain_available boolean, pickup_location text,
  dropoff_location text, distance_km numeric(10,2),
  constraint deliveries_orders_fk foreign key (order_id)
    references public.orders (order_id) on update restrict on delete restrict
);

create table public.logistics_companies (
  logistics_company_id bigint generated by default as identity primary key,
  delivery_id bigint not null, company_name text, contact_person text,
  contact_number text, email text, service_areas text[], pricing_model text,
  cod_available boolean, rating numeric(3,2), status text,
  created_at timestamptz not null default now(),
  constraint logistics_companies_deliveries_fk foreign key (delivery_id)
    references public.deliveries (delivery_id) on update restrict on delete restrict
);

create table public.riders (
  rider_id bigint generated by default as identity primary key,
  logistics_company_id bigint not null, license_number text, full_name text,
  vehicle_type text, vehicle_plate_number text, availability_status text,
  rating numeric(3,2), first_name text, last_name text, contact_number text,
  email text, gps_lat numeric(10,7), gps_long numeric(10,7),
  total_deliveries bigint, employment_status text, profile_photo_url text,
  constraint riders_logistics_companies_fk foreign key (logistics_company_id)
    references public.logistics_companies (logistics_company_id)
      on update restrict on delete restrict
);

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'admin_roles','admins','users','buyers','farmers','farms','categories',
    'commodities','carts','cart_items','orders','order_items','reviews',
    'payments','deliveries','riders','logistics_companies'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
  end loop;
end $$;

commit;
