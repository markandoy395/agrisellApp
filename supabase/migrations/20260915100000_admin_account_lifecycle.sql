begin;

create table public.admin_account_lifecycle_events (
  event_id bigint generated by default as identity primary key,
  account_type text not null check (account_type in ('user', 'farmer', 'rider')),
  account_id text not null,
  action text not null check (action in ('profile_updated', 'active', 'suspended', 'deactivated')),
  previous_status text,
  reason text check (reason is null or char_length(btrim(reason)) between 1 and 1000),
  actor_email text not null,
  created_at timestamptz not null default now()
);
create index admin_account_lifecycle_account_idx
  on public.admin_account_lifecycle_events (account_type, account_id, created_at desc);

create table public.admin_verification_actions (
  action_id bigint generated by default as identity primary key,
  entity_type text not null check (entity_type in ('farmer', 'rider')),
  entity_id text not null,
  action text not null check (action in ('profile_updated', 'verified', 'rejected', 'needs_information', 'suspended', 'deactivated', 'reactivated')),
  previous_status text,
  reason text check (reason is null or char_length(btrim(reason)) between 1 and 1000),
  message text check (message is null or char_length(btrim(message)) between 1 and 1000),
  missing_items text[] not null default '{}',
  actor_email text not null,
  created_at timestamptz not null default now(),
  check (action <> 'rejected' or reason is not null),
  check (action not in ('suspended', 'deactivated') or reason is not null),
  check (action <> 'needs_information' or (message is not null and cardinality(missing_items) > 0))
);
create index admin_verification_actions_entity_idx
  on public.admin_verification_actions (entity_type, entity_id, created_at desc);

alter table public.admin_account_lifecycle_events enable row level security;
alter table public.admin_verification_actions enable row level security;
revoke all on public.admin_account_lifecycle_events from public, anon, authenticated;
revoke all on public.admin_verification_actions from public, anon, authenticated;

commit;
