begin;

create table public.marketplace_conversations (
  conversation_id bigint generated by default as identity primary key,
  buyer_user_id bigint not null references public.buyers (buyer_user_id) on delete restrict,
  farmer_user_id bigint not null references public.farmers (farmer_user_id) on delete restrict,
  farm_id bigint not null references public.farms (farm_id) on delete restrict,
  commodity_id bigint references public.commodities (commodity_id) on delete restrict,
  order_id bigint references public.orders (order_id) on delete restrict,
  buyer_last_read_at timestamptz,
  farmer_last_read_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index marketplace_conversations_context_key
  on public.marketplace_conversations (
    buyer_user_id,
    farm_id,
    coalesce(commodity_id, 0),
    coalesce(order_id, 0)
  );
create index marketplace_conversations_farmer_updated_idx
  on public.marketplace_conversations (farmer_user_id, updated_at desc);
create index marketplace_conversations_buyer_updated_idx
  on public.marketplace_conversations (buyer_user_id, updated_at desc);

create table public.marketplace_messages (
  message_id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.marketplace_conversations (conversation_id) on delete cascade,
  sender_role text not null check (sender_role in ('buyer', 'farmer')),
  body text not null check (char_length(btrim(body)) between 1 and 1000),
  sent_at timestamptz not null default now()
);

create index marketplace_messages_conversation_sent_idx
  on public.marketplace_messages (conversation_id, sent_at, message_id);

create or replace function private.validate_marketplace_conversation_context()
returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if not exists (
    select 1 from public.farms as farm
    where farm.farm_id = new.farm_id
      and farm.farmer_user_id = new.farmer_user_id
  ) then
    raise exception 'Conversation farm and farmer do not match';
  end if;
  if new.commodity_id is not null and not exists (
    select 1 from public.commodities as commodity
    where commodity.commodity_id = new.commodity_id
      and commodity.farm_id = new.farm_id
  ) then
    raise exception 'Conversation commodity does not belong to the farm';
  end if;
  if new.order_id is not null and not exists (
    select 1
    from public.orders as order_record
    join public.cart_items as cart_item
      on cart_item.cart_item_id = order_record.cart_item_id
    join public.carts as cart on cart.cart_id = cart_item.cart_id
    join public.commodities as commodity
      on commodity.commodity_id = cart_item.commodity_id
    where order_record.order_id = new.order_id
      and cart.buyer_user_id = new.buyer_user_id
      and commodity.farm_id = new.farm_id
      and (
        new.commodity_id is null
        or commodity.commodity_id = new.commodity_id
      )
  ) then
    raise exception 'Conversation order context is invalid';
  end if;
  return new;
end;
$$;

create trigger marketplace_conversations_validate_context
before insert or update of buyer_user_id, farmer_user_id, farm_id,
  commodity_id, order_id on public.marketplace_conversations
for each row execute function private.validate_marketplace_conversation_context();

alter table public.marketplace_conversations enable row level security;
alter table public.marketplace_messages enable row level security;

create or replace function private.can_access_marketplace_conversation(
  target_conversation_id bigint
)
returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1
    from public.marketplace_conversations as conversation
    where conversation.conversation_id = target_conversation_id
      and (
        conversation.buyer_user_id = private.current_buyer_user_id()
        or conversation.farmer_user_id = private.current_farmer_user_id()
      )
  )
$$;

create policy marketplace_conversations_participant_read
on public.marketplace_conversations for select to authenticated
using (
  buyer_user_id = private.current_buyer_user_id()
  or farmer_user_id = private.current_farmer_user_id()
);

create policy marketplace_messages_participant_read
on public.marketplace_messages for select to authenticated
using (private.can_access_marketplace_conversation(conversation_id));

revoke all on public.marketplace_conversations from public, anon;
revoke all on public.marketplace_messages from public, anon;
grant select on public.marketplace_conversations to authenticated;
grant select on public.marketplace_messages to authenticated;

create or replace function private.start_marketplace_conversation(
  p_commodity_id bigint default null,
  p_farm_id bigint default null,
  p_client_order_id text default null
)
returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  actor_buyer_id bigint := private.current_buyer_user_id();
  resolved_farm_id bigint;
  resolved_farmer_id bigint;
  resolved_order_id bigint;
  result_id bigint;
begin
  if actor_buyer_id is null then
    raise exception 'Only buyers can start marketplace conversations';
  end if;
  if p_commodity_id is null and p_farm_id is null then
    raise exception 'A commodity or farm is required';
  end if;

  select commodity.farm_id
  into resolved_farm_id
  from public.commodities as commodity
  where commodity.commodity_id = p_commodity_id;
  resolved_farm_id := coalesce(resolved_farm_id, p_farm_id);

  select farm.farmer_user_id
  into resolved_farmer_id
  from public.farms as farm
  join public.farmers as farmer
    on farmer.farmer_user_id = farm.farmer_user_id
  where farm.farm_id = resolved_farm_id
    and (p_farm_id is null or farm.farm_id = p_farm_id)
    and (
      p_client_order_id is not null
      or (
        lower(coalesce(farmer.verification_status, 'pending')) = 'verified'
        and lower(coalesce(farmer.account_status, 'active')) = 'active'
      )
    );
  if resolved_farmer_id is null then
    raise exception 'The selected farmer is unavailable';
  end if;

  if p_client_order_id is not null then
    select min(order_record.order_id)
    into resolved_order_id
    from public.orders as order_record
    join public.cart_items as cart_item
      on cart_item.cart_item_id = order_record.cart_item_id
    join public.carts as cart on cart.cart_id = cart_item.cart_id
    join public.commodities as commodity
      on commodity.commodity_id = cart_item.commodity_id
    where order_record.client_order_id = p_client_order_id
      and cart.buyer_user_id = actor_buyer_id
      and commodity.farm_id = resolved_farm_id
      and (p_commodity_id is null or commodity.commodity_id = p_commodity_id);
    if resolved_order_id is null then
      raise exception 'The selected order cannot be messaged';
    end if;
  end if;

  insert into public.marketplace_conversations (
    buyer_user_id, farmer_user_id, farm_id, commodity_id, order_id
  ) values (
    actor_buyer_id, resolved_farmer_id, resolved_farm_id,
    p_commodity_id, resolved_order_id
  )
  on conflict do nothing
  returning conversation_id into result_id;

  if result_id is null then
    select conversation.conversation_id
    into result_id
    from public.marketplace_conversations as conversation
    where conversation.buyer_user_id = actor_buyer_id
      and conversation.farm_id = resolved_farm_id
      and conversation.commodity_id is not distinct from p_commodity_id
      and conversation.order_id is not distinct from resolved_order_id;
  end if;
  return result_id;
end;
$$;

create or replace function private.current_marketplace_conversations()
returns jsonb
language sql stable security definer set search_path = '' as $$
  with actor as (
    select private.current_buyer_user_id() as buyer_id,
      private.current_farmer_user_id() as farmer_id
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'conversation_id', conversation.conversation_id::text,
    'buyer_name', coalesce(nullif(btrim(concat_ws(' ', buyer_user.first_name,
      buyer_user.last_name)), ''), 'Buyer'),
    'buyer_image_url', buyer_user.profile_photo_url,
    'farmer_name', coalesce(nullif(btrim(concat_ws(' ', farmer.first_name,
      farmer.last_name)), ''), nullif(farm.farm_name, ''), 'Farmer'),
    'farmer_image_url', farmer.profile_image_url,
    'farm_name', coalesce(nullif(farm.farm_name, ''), 'Farm'),
    'farm_location', coalesce(nullif(farm.farm_location, ''), 'Location unavailable'),
    'commodity_id', commodity.commodity_id::text,
    'product_name', commodity.commodity_name,
    'product_image_url', commodity.image_url,
    'unit_type', commodity.unit_type,
    'order_reference', order_record.client_order_id,
    'order_status', order_record.order_status,
    'quantity', cart_item.quantity,
    'unit_price', coalesce(cart_item.price_at_time, commodity.price_per_unit),
    'last_message', coalesce(last_message.body, ''),
    'last_message_at', coalesce(last_message.sent_at, conversation.updated_at),
    'unread_count', coalesce(unread.unread_count, 0)
  ) order by coalesce(last_message.sent_at, conversation.updated_at) desc), '[]'::jsonb)
  from public.marketplace_conversations as conversation
  cross join actor
  join public.buyers as buyer on buyer.buyer_user_id = conversation.buyer_user_id
  join public.users as buyer_user on buyer_user.user_id = buyer.user_id
  join public.farmers as farmer on farmer.farmer_user_id = conversation.farmer_user_id
  join public.farms as farm on farm.farm_id = conversation.farm_id
  left join public.orders as order_record on order_record.order_id = conversation.order_id
  left join public.cart_items as cart_item
    on cart_item.cart_item_id = order_record.cart_item_id
  left join public.commodities as commodity
    on commodity.commodity_id = coalesce(
      conversation.commodity_id,
      cart_item.commodity_id
    )
  left join lateral (
    select message.body, message.sent_at
    from public.marketplace_messages as message
    where message.conversation_id = conversation.conversation_id
    order by message.sent_at desc, message.message_id desc limit 1
  ) as last_message on true
  left join lateral (
    select count(*)::integer as unread_count
    from public.marketplace_messages as message
    where message.conversation_id = conversation.conversation_id
      and message.sender_role = case when actor.buyer_id is not null
        then 'farmer' else 'buyer' end
      and message.sent_at > coalesce(
        case when actor.buyer_id is not null then conversation.buyer_last_read_at
          else conversation.farmer_last_read_at end,
        '-infinity'::timestamptz
      )
  ) as unread on true
  where conversation.buyer_user_id = actor.buyer_id
    or conversation.farmer_user_id = actor.farmer_id
$$;

create or replace function private.marketplace_conversation_messages(
  p_conversation_id bigint
)
returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare result jsonb;
begin
  if not private.can_access_marketplace_conversation(p_conversation_id) then
    raise exception 'Conversation not found';
  end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'message_id', message.message_id::text,
    'sender_role', message.sender_role,
    'body', message.body,
    'sent_at', message.sent_at
  ) order by message.sent_at, message.message_id), '[]'::jsonb)
  into result
  from public.marketplace_messages as message
  where message.conversation_id = p_conversation_id;
  return result;
end;
$$;

create or replace function private.mark_marketplace_conversation_read(
  p_conversation_id bigint
)
returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not private.can_access_marketplace_conversation(p_conversation_id) then
    raise exception 'Conversation not found';
  end if;
  update public.marketplace_conversations as conversation
  set buyer_last_read_at = case when conversation.buyer_user_id = private.current_buyer_user_id()
      then now() else conversation.buyer_last_read_at end,
    farmer_last_read_at = case when conversation.farmer_user_id = private.current_farmer_user_id()
      then now() else conversation.farmer_last_read_at end
  where conversation.conversation_id = p_conversation_id;
end;
$$;

create or replace function private.send_marketplace_message(
  p_conversation_id bigint,
  p_body text
)
returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  actor_role text;
  actor_is_buyer boolean;
  actor_is_farmer boolean;
  saved public.marketplace_messages;
begin
  if not private.can_access_marketplace_conversation(p_conversation_id) then
    raise exception 'Conversation not found';
  end if;
  if char_length(btrim(coalesce(p_body, ''))) not between 1 and 1000 then
    raise exception 'Messages must contain between 1 and 1000 characters';
  end if;
  select
    conversation.buyer_user_id = private.current_buyer_user_id(),
    conversation.farmer_user_id = private.current_farmer_user_id()
  into actor_is_buyer, actor_is_farmer
  from public.marketplace_conversations as conversation
  where conversation.conversation_id = p_conversation_id;
  if coalesce(actor_is_buyer, false) = coalesce(actor_is_farmer, false) then
    raise exception 'Messaging identity is ambiguous or unavailable';
  end if;
  actor_role := case when actor_is_buyer then 'buyer' else 'farmer' end;

  insert into public.marketplace_messages (conversation_id, sender_role, body)
  values (p_conversation_id, actor_role, btrim(p_body)) returning * into saved;
  update public.marketplace_conversations
  set updated_at = saved.sent_at,
    buyer_last_read_at = case when actor_role = 'buyer' then saved.sent_at
      else buyer_last_read_at end,
    farmer_last_read_at = case when actor_role = 'farmer' then saved.sent_at
      else farmer_last_read_at end
  where conversation_id = p_conversation_id;

  return jsonb_build_object('message_id', saved.message_id::text,
    'sender_role', saved.sender_role, 'body', saved.body, 'sent_at', saved.sent_at);
end;
$$;

