create table if not exists public.admin_security_events (
  event_id bigint generated by default as identity primary key,
  actor_email text not null,
  action text not null,
  detail text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists admin_security_events_actor_created_idx
  on public.admin_security_events (actor_email, created_at desc);

create table if not exists public.admin_requests (
  request_id bigint generated by default as identity primary key,
  submitted_by_email text not null,
  request_type text not null check (request_type in ('support', 'feature')),
  subject text not null check (char_length(subject) between 1 and 160),
  message text not null check (char_length(message) between 1 and 5000),
  status text not null default 'open' check (status in ('open', 'in_progress', 'resolved', 'closed')),
  created_at timestamptz not null default now()
);

create index if not exists admin_requests_status_created_idx
  on public.admin_requests (status, created_at desc);

alter table public.admin_security_events enable row level security;
alter table public.admin_requests enable row level security;

revoke all on public.admin_security_events from anon, authenticated;
revoke all on public.admin_requests from anon, authenticated;
grant all on public.admin_security_events to service_role;
grant all on public.admin_requests to service_role;
grant usage, select on sequence public.admin_security_events_event_id_seq to service_role;
grant usage, select on sequence public.admin_requests_request_id_seq to service_role;
