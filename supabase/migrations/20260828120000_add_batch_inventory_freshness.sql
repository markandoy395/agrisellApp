begin;

alter table public.commodities
  add column if not exists inventory_date_type text not null
    default 'fresh_produce';

alter table public.commodities
  drop constraint if exists commodities_inventory_date_type_check;
alter table public.commodities
  add constraint commodities_inventory_date_type_check check (
    inventory_date_type in ('fresh_produce', 'packaged_food', 'non_perishable')
  );

update public.commodities as commodity
set inventory_date_type = 'non_perishable'
from public.categories as category
where category.category_id = commodity.category_id
  and category.farm_id = commodity.farm_id
  and lower(coalesce(category.category_name, '')) = 'fruit trees';

create table public.commodity_inventory_lots (
  inventory_lot_id bigint generated by default as identity primary key,
  commodity_id bigint not null references public.commodities (commodity_id)
    on update restrict on delete restrict,
  date_type text not null,
  quantity_received numeric(14,3) not null check (quantity_received > 0),
  quantity_remaining numeric(14,3) not null check (quantity_remaining >= 0),
  harvested_at date,
  sell_until date,
  expires_at date,
  lot_code text,
  storage_instructions text,
  created_by uuid references auth.users (id) on delete restrict,
  created_at timestamptz not null default now(),
  expired_at timestamptz,
  constraint commodity_inventory_lots_quantity_check
    check (quantity_remaining <= quantity_received),
  constraint commodity_inventory_lots_date_type_check check (
    date_type in (
      'fresh_produce', 'packaged_food', 'non_perishable', 'legacy_undated'
    )
  ),
  constraint commodity_inventory_lots_lot_code_length_check
    check (lot_code is null or length(lot_code) <= 80),
  constraint commodity_inventory_lots_storage_length_check
    check (storage_instructions is null or length(storage_instructions) <= 240),
  constraint commodity_inventory_lots_sell_date_check
    check (sell_until is null or harvested_at is null or sell_until >= harvested_at),
  constraint commodity_inventory_lots_expiry_date_check
    check (expires_at is null or harvested_at is null or expires_at >= harvested_at)
);

create index commodity_inventory_lots_marketplace_idx
  on public.commodity_inventory_lots (
    commodity_id, expired_at, sell_until, expires_at, quantity_remaining
  );

alter table public.commodity_inventory_lots enable row level security;
revoke all on public.commodity_inventory_lots from public, anon, authenticated;
create policy "deny direct client access"
on public.commodity_inventory_lots as restrictive for all
to public using (false) with check (false);

insert into public.commodity_inventory_lots (
  commodity_id, date_type, quantity_received, quantity_remaining, harvested_at
)
select commodity.commodity_id, 'legacy_undated', commodity.available_quantity,
  commodity.available_quantity, commodity.harvest_date
from public.commodities as commodity
where commodity.available_quantity > 0
  and not exists (
    select 1 from public.commodity_inventory_lots as lot
    where lot.commodity_id = commodity.commodity_id
  );

create table private.order_inventory_lot_allocations (
  allocation_id bigint generated by default as identity primary key,
  order_item_id bigint not null references public.order_items (order_item_id)
    on update restrict on delete restrict,
  inventory_lot_id bigint not null
    references public.commodity_inventory_lots (inventory_lot_id)
    on update restrict on delete restrict,
  quantity numeric(14,3) not null check (quantity > 0),
  allocated_at timestamptz not null default now(),
  released_at timestamptz,
  unique (order_item_id, inventory_lot_id)
);

create index order_inventory_lot_allocations_lot_idx
  on private.order_inventory_lot_allocations (inventory_lot_id, released_at);

alter table private.order_inventory_lot_allocations enable row level security;
revoke all on private.order_inventory_lot_allocations
  from public, anon, authenticated;
create policy "deny direct client access"
on private.order_inventory_lot_allocations as restrictive for all
to public using (false) with check (false);

create or replace function private.inventory_lot_is_marketable(
  target_lot public.commodity_inventory_lots,
  on_date date default current_date
) returns boolean language sql stable security definer set search_path = '' as $$
  select target_lot.expired_at is null
    and target_lot.quantity_remaining > 0
    and (target_lot.sell_until is null or target_lot.sell_until >= on_date)
    and (target_lot.expires_at is null or target_lot.expires_at >= on_date)
$$;

create or replace function private.add_current_farmer_inventory_lot(
  p_commodity_id bigint,
  p_quantity numeric,
  p_date_type text,
  p_harvested_at date,
  p_sell_until date,
  p_expires_at date,
  p_lot_code text,
  p_storage_instructions text,
  p_reason text
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  commodity_record public.commodities%rowtype;
  previous_quantity numeric(14,3);
  resulting_quantity numeric(14,3);
  normalized_lot_code text := nullif(btrim(coalesce(p_lot_code, '')), '');
  normalized_storage text := nullif(btrim(coalesce(p_storage_instructions, '')), '');
  normalized_reason text := nullif(btrim(coalesce(p_reason, '')), '');
  new_lot_id bigint;
begin
  if (select auth.uid()) is null then
    raise exception 'An authenticated farmer account is required'
      using errcode = '42501';
  end if;
  if p_commodity_id is null or p_commodity_id <= 0 then
    raise exception 'Select a valid product to restock' using errcode = '22023';
  end if;
  if p_quantity is null or p_quantity <= 0 or p_quantity > 1000000
     or scale(p_quantity) > 3 then
    raise exception 'Restock quantity must be at most 1,000,000 with up to 3 decimal places'
      using errcode = '22023';
  end if;
  if p_date_type not in ('fresh_produce', 'packaged_food', 'non_perishable') then
    raise exception 'Select a valid inventory date type' using errcode = '22023';
  end if;
  if normalized_reason is not null and length(normalized_reason) > 240 then
    raise exception 'Restock notes must be 240 characters or fewer'
      using errcode = '22023';
  end if;
  if normalized_storage is not null and length(normalized_storage) > 240 then
    raise exception 'Storage instructions must be 240 characters or fewer'
      using errcode = '22023';
  end if;
  if normalized_lot_code is not null and length(normalized_lot_code) > 80 then
    raise exception 'Lot code must be 80 characters or fewer'
      using errcode = '22023';
  end if;
  if p_date_type <> 'non_perishable' and p_harvested_at is null then
    raise exception 'Select the harvest or production date' using errcode = '22023';
  end if;
  if p_date_type = 'fresh_produce' and (
    p_sell_until is null or p_sell_until < current_date
    or p_sell_until < p_harvested_at
  ) then
    raise exception 'Fresh produce needs a valid final selling date'
      using errcode = '22023';
  end if;
  if p_date_type = 'packaged_food' and (
    p_expires_at is null or p_expires_at < current_date
    or p_expires_at < p_harvested_at or normalized_lot_code is null
  ) then
    raise exception 'Packaged food needs a valid expiration date and lot code'
      using errcode = '22023';
  end if;

  select commodity.* into commodity_record
  from public.commodities as commodity
  where commodity.commodity_id = p_commodity_id
  for update;

  if not found then
    raise exception 'The selected product no longer exists' using errcode = '22023';
  end if;
  if not private.owns_farm(commodity_record.farm_id)
     and not private.is_admin() then
    raise exception 'You are not authorized to restock this product'
      using errcode = '42501';
  end if;
  if p_date_type = 'non_perishable' and exists (
    select 1 from public.categories as category
    where category.category_id = commodity_record.category_id
      and category.farm_id = commodity_record.farm_id
      and lower(coalesce(category.category_name, '')) in (
        'vegetables', 'fruits', 'nuts', 'spices'
      )
  ) then
    raise exception 'Edible products require freshness or expiration tracking'
      using errcode = '22023';
  end if;
  if lower(coalesce(commodity_record.commodity_status, 'available')) = 'sold' then
    raise exception 'Mark this product as unsold before adding stock'
      using errcode = '22023';
  end if;

  previous_quantity := commodity_record.available_quantity;
  resulting_quantity := previous_quantity + p_quantity;
  if resulting_quantity > 1000000 then
    raise exception 'Resulting stock cannot exceed 1,000,000' using errcode = '22023';
  end if;

  insert into public.commodity_inventory_lots (
    commodity_id, date_type, quantity_received, quantity_remaining,
    harvested_at, sell_until, expires_at, lot_code, storage_instructions,
    created_by
  ) values (
    p_commodity_id, p_date_type, p_quantity, p_quantity, p_harvested_at,
    p_sell_until, p_expires_at, normalized_lot_code, normalized_storage,
    (select auth.uid())
  ) returning inventory_lot_id into new_lot_id;

  update public.commodities
  set available_quantity = resulting_quantity,
      inventory_date_type = p_date_type,
      updated_at = now()
  where commodity_id = p_commodity_id;

  insert into private.commodity_restock_history (
    commodity_id, quantity_added, previous_quantity, new_quantity,
    performed_by, reason
  ) values (
    p_commodity_id, p_quantity, previous_quantity, resulting_quantity,
    (select auth.uid()), normalized_reason
  );

  return jsonb_build_object(
    'commodity_id', p_commodity_id,
    'inventory_lot_id', new_lot_id,
    'previous_quantity', previous_quantity,
    'quantity_added', p_quantity,
    'new_quantity', resulting_quantity,
    'commodity_status', 'available'
  );
end;
$$;

create or replace function public.restock_current_farmer_inventory_lot(
  p_commodity_id bigint,
  p_quantity numeric,
  p_date_type text,
  p_harvested_at date,
  p_sell_until date,
  p_expires_at date,
  p_lot_code text,
  p_storage_instructions text,
  p_reason text
) returns jsonb language sql security definer set search_path = '' as $$
  select private.add_current_farmer_inventory_lot(
    p_commodity_id, p_quantity, p_date_type, p_harvested_at, p_sell_until,
    p_expires_at, p_lot_code, p_storage_instructions, p_reason
  )
$$;

create or replace function public.restock_current_farmer_commodity(
  p_commodity_id bigint,
  p_quantity numeric,
  p_reason text default null
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare date_type text;
begin
  select commodity.inventory_date_type into date_type
  from public.commodities as commodity
  where commodity.commodity_id = p_commodity_id;
  if date_type is distinct from 'non_perishable' then
    raise exception 'Update AgriSell to provide this stock batch freshness information'
      using errcode = '22023';
  end if;
  return private.add_current_farmer_inventory_lot(
    p_commodity_id, p_quantity, 'non_perishable', null, null, null,
    null, null, p_reason
  );
end;
$$;

create or replace function private.allocate_order_inventory_lots()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  target_commodity_id bigint;
  quantity_to_allocate numeric(14,3) := new.quantity;
  lot_record record;
  allocated_quantity numeric(14,3);
begin
  select cart_item.commodity_id into target_commodity_id
  from public.orders as order_record
  join public.cart_items as cart_item
    on cart_item.cart_item_id = order_record.cart_item_id
  where order_record.order_id = new.order_id;

  if target_commodity_id is null then
    raise exception 'The ordered product could not be resolved' using errcode = '22023';
  end if;

  for lot_record in
    select lot.inventory_lot_id, lot.quantity_remaining
    from public.commodity_inventory_lots as lot
    where lot.commodity_id = target_commodity_id
      and private.inventory_lot_is_marketable(lot, current_date)
    order by coalesce(lot.expires_at, lot.sell_until, 'infinity'::date),
      lot.harvested_at nulls last, lot.inventory_lot_id
    for update
  loop
    exit when quantity_to_allocate <= 0;
    allocated_quantity := least(quantity_to_allocate, lot_record.quantity_remaining);
    update public.commodity_inventory_lots
    set quantity_remaining = quantity_remaining - allocated_quantity
    where inventory_lot_id = lot_record.inventory_lot_id;
    insert into private.order_inventory_lot_allocations (
      order_item_id, inventory_lot_id, quantity
    ) values (new.order_item_id, lot_record.inventory_lot_id, allocated_quantity);
    quantity_to_allocate := quantity_to_allocate - allocated_quantity;
  end loop;

  if quantity_to_allocate > 0 then
    raise exception 'This product no longer has enough unexpired stock'
      using errcode = '22023';
  end if;
  return new;
end;
$$;

drop trigger if exists order_items_allocate_inventory_lots on public.order_items;
create trigger order_items_allocate_inventory_lots
after insert on public.order_items
for each row execute function private.allocate_order_inventory_lots();

create or replace function private.release_order_inventory_lots()
returns trigger language plpgsql security definer set search_path = '' as $$
declare allocation record;
begin
  if old.stock_released_at is not null or new.stock_released_at is null then
    return new;
  end if;
  for allocation in
    select allocated.allocation_id, allocated.inventory_lot_id,
      allocated.quantity, lot.commodity_id, lot.sell_until, lot.expires_at,
      lot.expired_at
    from public.order_items as item
    join private.order_inventory_lot_allocations as allocated
      on allocated.order_item_id = item.order_item_id
    join public.commodity_inventory_lots as lot
      on lot.inventory_lot_id = allocated.inventory_lot_id
    where item.order_id = new.order_id and allocated.released_at is null
    for update of allocated, lot
  loop
    if allocation.expired_at is null
       and (allocation.sell_until is null or allocation.sell_until >= current_date)
       and (allocation.expires_at is null or allocation.expires_at >= current_date) then
      update public.commodity_inventory_lots
      set quantity_remaining = quantity_remaining + allocation.quantity
      where inventory_lot_id = allocation.inventory_lot_id;
    else
      update public.commodities
      set available_quantity = greatest(0, available_quantity - allocation.quantity)
      where commodity_id = allocation.commodity_id;
    end if;
    update private.order_inventory_lot_allocations
    set released_at = now()
    where allocation_id = allocation.allocation_id;
  end loop;
  return new;
end;
$$;

drop trigger if exists orders_release_inventory_lots on public.orders;
create trigger orders_release_inventory_lots
after update of stock_released_at on public.orders
for each row execute function private.release_order_inventory_lots();

create or replace function private.expire_commodity_inventory_lots()
returns integer language plpgsql volatile security definer set search_path = '' as $$
declare lot_record record;
declare expired_count integer := 0;
begin
  for lot_record in
    select lot.inventory_lot_id, lot.commodity_id, lot.quantity_remaining
    from public.commodity_inventory_lots as lot
    where lot.expired_at is null and lot.quantity_remaining > 0
      and (
        (lot.sell_until is not null and lot.sell_until < current_date)
        or (lot.expires_at is not null and lot.expires_at < current_date)
      )
    order by lot.commodity_id, lot.inventory_lot_id
    for update
  loop
    update public.commodity_inventory_lots
    set quantity_remaining = 0, expired_at = now()
    where inventory_lot_id = lot_record.inventory_lot_id;
    update public.commodities
    set available_quantity = greatest(
      0, available_quantity - lot_record.quantity_remaining
    )
    where commodity_id = lot_record.commodity_id;
    expired_count := expired_count + 1;
  end loop;
  return expired_count;
end;
$$;

create or replace function public.marketplace_inventory_lot_summaries(
  p_commodity_ids bigint[]
) returns table (
  commodity_id bigint,
  marketable_quantity numeric,
  inventory_date_type text,
  next_harvested_at date,
  next_sell_until date,
  next_expires_at date,
  next_lot_code text,
  storage_instructions text
) language sql stable security definer set search_path = '' as $$
  select commodity.commodity_id,
    coalesce(sum(lot.quantity_remaining) filter (
      where private.inventory_lot_is_marketable(lot, current_date)
    ), 0),
    commodity.inventory_date_type,
    (array_agg(lot.harvested_at order by
      coalesce(lot.expires_at, lot.sell_until, 'infinity'::date),
      lot.inventory_lot_id) filter (
        where private.inventory_lot_is_marketable(lot, current_date)
      ))[1],
    min(lot.sell_until) filter (
      where private.inventory_lot_is_marketable(lot, current_date)
    ),
    min(lot.expires_at) filter (
      where private.inventory_lot_is_marketable(lot, current_date)
    ),
    (array_agg(lot.lot_code order by
      coalesce(lot.expires_at, lot.sell_until, 'infinity'::date),
      lot.inventory_lot_id) filter (
        where private.inventory_lot_is_marketable(lot, current_date)
          and lot.lot_code is not null
      ))[1],
    (array_agg(lot.storage_instructions order by
      coalesce(lot.expires_at, lot.sell_until, 'infinity'::date),
      lot.inventory_lot_id) filter (
        where private.inventory_lot_is_marketable(lot, current_date)
          and lot.storage_instructions is not null
      ))[1]
  from public.commodities as commodity
  left join public.commodity_inventory_lots as lot
    on lot.commodity_id = commodity.commodity_id
  where commodity.commodity_id = any(coalesce(p_commodity_ids, '{}'::bigint[]))
  group by commodity.commodity_id, commodity.inventory_date_type
$$;

create or replace function public.marketplace_products(p_farm_id bigint default null)
returns table (
  commodity_id bigint, commodity_name text, description text, price_per_unit numeric,
  effective_price numeric, unit_type text, image_url text, harvest_date date,
  available_quantity numeric, farm_id bigint, commodity_status text,
  availability_status text, production_status text, rating numeric, category_name text
) language sql stable security definer set search_path = '' as $$
  select commodity.commodity_id, commodity.commodity_name, commodity.description,
    commodity.price_per_unit,
    private.effective_commodity_price(commodity.commodity_id, private.current_buyer_user_id()),
    commodity.unit_type, commodity.image_url, commodity.harvest_date,
    lot_summary.marketable_quantity, commodity.farm_id, commodity.commodity_status,
    commodity.availability_status, commodity.production_status, commodity.rating,
    category.category_name
  from public.commodities as commodity
  left join public.categories as category
    on category.category_id = commodity.category_id
      and category.farm_id = commodity.farm_id
  cross join lateral (
    select coalesce(sum(lot.quantity_remaining) filter (
      where private.inventory_lot_is_marketable(lot, current_date)
    ), 0) as marketable_quantity
    from public.commodity_inventory_lots as lot
    where lot.commodity_id = commodity.commodity_id
  ) as lot_summary
  where lower(coalesce(commodity.commodity_status, '')) = 'available'
    and lot_summary.marketable_quantity > 0
    and commodity.availability_status <> 'not_accepting_orders'
    and (p_farm_id is null or commodity.farm_id = p_farm_id)
  order by commodity.created_at desc
$$;

