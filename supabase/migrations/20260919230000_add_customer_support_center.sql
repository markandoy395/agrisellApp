begin;

-- 1. Support Tickets Table
create table if not exists public.support_tickets (
  ticket_id bigint generated by default as identity primary key,
  ticket_number text unique not null,
  user_id bigint not null references public.users(user_id) on delete cascade,
  user_role text not null check (user_role in ('buyer', 'farmer', 'rider', 'general')),
  subject text not null check (char_length(btrim(subject)) between 2 and 255),
  category text not null check (category in ('order', 'delivery', 'payment', 'account', 'safety', 'general')),
  status text not null default 'open' check (status in ('open', 'in_progress', 'waiting_on_customer', 'resolved', 'closed')),
  priority text not null default 'medium' check (priority in ('low', 'medium', 'high', 'urgent')),
  assigned_admin text,
  resolution_notes text,
  order_id bigint references public.orders(order_id) on delete set null,
  delivery_id bigint references public.deliveries(delivery_id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);

-- 2. Support Messages Table
create table if not exists public.support_messages (
  message_id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.support_tickets(ticket_id) on delete cascade,
  sender_role text not null check (sender_role in ('user', 'support', 'system')),
  sender_name text not null,
  sender_user_id bigint references public.users(user_id) on delete set null,
  body text not null check (char_length(btrim(body)) between 1 and 4000),
  attachments jsonb default '[]'::jsonb,
  created_at timestamptz not null default now()
);

-- Indexes
create index if not exists support_tickets_status_idx on public.support_tickets(status, updated_at desc);
create index if not exists support_tickets_user_idx on public.support_tickets(user_id);
create index if not exists support_messages_ticket_idx on public.support_messages(ticket_id, created_at asc);

-- Row Level Security
alter table public.support_tickets enable row level security;
alter table public.support_messages enable row level security;

create policy support_tickets_participant_read on public.support_tickets
  for select to authenticated
  using (
    user_id = (select user_id from private.auth_identities where auth_user_id = auth.uid())
    or private.is_admin()
  );

create policy support_tickets_participant_insert on public.support_tickets
  for insert to authenticated
  with check (
    user_id = (select user_id from private.auth_identities where auth_user_id = auth.uid())
    or private.is_admin()
  );

create policy support_messages_participant_read on public.support_messages
  for select to authenticated
  using (
    exists (
      select 1 from public.support_tickets t
      where t.ticket_id = support_messages.ticket_id
        and (t.user_id = (select user_id from private.auth_identities where auth_user_id = auth.uid()) or private.is_admin())
    )
  );

create policy support_messages_participant_insert on public.support_messages
  for insert to authenticated
  with check (
    exists (
      select 1 from public.support_tickets t
      where t.ticket_id = support_messages.ticket_id
        and (t.user_id = (select user_id from private.auth_identities where auth_user_id = auth.uid()) or private.is_admin())
    )
  );

-- 3. Admin Support Hub RPC
create or replace function public.admin_get_support_hub()
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  tickets_json jsonb;
  delivery_chats_json jsonb;
  stats_json jsonb;
begin
  -- Collect tickets with customer info and last message
  select coalesce(jsonb_agg(jsonb_build_object(
    'ticket_id', t.ticket_id,
    'ticket_number', t.ticket_number,
    'user_id', t.user_id,
    'user_role', t.user_role,
    'customer_name', coalesce(nullif(btrim(u.first_name || ' ' || coalesce(u.last_name, '')), ''), 'Customer ' || t.user_id),
    'customer_email', u.email,
    'customer_phone', u.contact_number,
    'subject', t.subject,
    'category', t.category,
    'status', t.status,
    'priority', t.priority,
    'assigned_admin', t.assigned_admin,
    'order_id', t.order_id,
    'delivery_id', t.delivery_id,
    'created_at', t.created_at,
    'updated_at', t.updated_at,
    'resolved_at', t.resolved_at,
    'message_count', (select count(*) from public.support_messages m where m.ticket_id = t.ticket_id),
    'last_message_preview', (
      select m.body from public.support_messages m
      where m.ticket_id = t.ticket_id
      order by m.created_at desc limit 1
    ),
    'last_message_time', (
      select m.created_at from public.support_messages m
      where m.ticket_id = t.ticket_id
      order by m.created_at desc limit 1
    ),
    'last_sender_role', (
      select m.sender_role from public.support_messages m
      where m.ticket_id = t.ticket_id
      order by m.created_at desc limit 1
    )
  ) order by t.updated_at desc), '[]'::jsonb)
  into tickets_json
  from public.support_tickets t
  join public.users u on u.user_id = t.user_id;

  -- Collect active rider delivery support chats
  select coalesce(jsonb_agg(jsonb_build_object(
    'conversation_id', 'delivery:' || m.delivery_id || ':support',
    'delivery_id', m.delivery_id,
    'rider_id', a.rider_id,
    'rider_name', r.full_name,
    'rider_phone', r.contact_number,
    'last_message', m.body,
    'last_activity', m.sent_at,
    'last_sender_role', m.sender_role,
    'order_id', d.order_id,
    'delivery_status', d.delivery_status
  ) order by m.sent_at desc), '[]'::jsonb)
  into delivery_chats_json
  from (
    select distinct on (delivery_id) *
    from public.rider_delivery_messages
    where party = 'support'
    order by delivery_id, sent_at desc
  ) m
  join public.deliveries d on d.delivery_id = m.delivery_id
  left join private.rider_delivery_assignments a on a.delivery_id = m.delivery_id
  left join public.riders r on r.rider_id = a.rider_id;

  -- Calculate summary stats
  select jsonb_build_object(
    'total', count(*),
    'open', count(*) filter (where status = 'open'),
    'in_progress', count(*) filter (where status = 'in_progress'),
    'waiting_on_customer', count(*) filter (where status = 'waiting_on_customer'),
    'resolved', count(*) filter (where status in ('resolved', 'closed')),
    'urgent', count(*) filter (where priority = 'urgent' and status not in ('resolved', 'closed'))
  )
  into stats_json
  from public.support_tickets;

  return jsonb_build_object(
    'tickets', tickets_json,
    'delivery_chats', delivery_chats_json,
    'stats', stats_json
  );
end;
$$;

-- 4. Admin Get Support Ticket Detail RPC
create or replace function public.admin_get_support_ticket_detail(p_ticket_id bigint)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  ticket_json jsonb;
  messages_json jsonb;
begin
  select jsonb_build_object(
    'ticket_id', t.ticket_id,
    'ticket_number', t.ticket_number,
    'user_id', t.user_id,
    'user_role', t.user_role,
    'customer_name', coalesce(nullif(btrim(u.first_name || ' ' || coalesce(u.last_name, '')), ''), 'Customer ' || t.user_id),
    'customer_email', u.email,
    'customer_phone', u.contact_number,
    'subject', t.subject,
    'category', t.category,
    'status', t.status,
    'priority', t.priority,
    'assigned_admin', t.assigned_admin,
    'resolution_notes', t.resolution_notes,
    'order_id', t.order_id,
    'delivery_id', t.delivery_id,
    'created_at', t.created_at,
    'updated_at', t.updated_at,
    'resolved_at', t.resolved_at
  )
  into ticket_json
  from public.support_tickets t
  join public.users u on u.user_id = t.user_id
  where t.ticket_id = p_ticket_id;

  if ticket_json is null then
    return null;
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'message_id', m.message_id,
    'ticket_id', m.ticket_id,
    'sender_role', m.sender_role,
    'sender_name', m.sender_name,
    'sender_user_id', m.sender_user_id,
    'body', m.body,
    'attachments', m.attachments,
    'created_at', m.created_at
  ) order by m.created_at asc), '[]'::jsonb)
  into messages_json
  from public.support_messages m
  where m.ticket_id = p_ticket_id;

  return jsonb_build_object(
    'ticket', ticket_json,
    'messages', messages_json
  );
end;
$$;

-- 5. Admin Send Support Message RPC
create or replace function public.admin_send_support_message(
  p_ticket_id bigint,
  p_body text,
  p_actor text
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  saved_msg public.support_messages%rowtype;
  ticket_record public.support_tickets%rowtype;
  sender_display text := coalesce(nullif(btrim(p_actor), ''), 'Agrisell Support');
begin
  if p_body is null or length(btrim(p_body)) = 0 then
    raise exception 'Message content is required' using errcode = '22023';
  end if;

  select * into ticket_record from public.support_tickets where ticket_id = p_ticket_id for update;
  if not found then
    raise exception 'Ticket not found' using errcode = '22023';
  end if;

  insert into public.support_messages(
    ticket_id, sender_role, sender_name, body
  ) values (
    p_ticket_id, 'support', sender_display, btrim(p_body)
  ) returning * into saved_msg;

  update public.support_tickets
  set updated_at = now(),
      status = case when status = 'open' then 'in_progress' else status end,
      assigned_admin = coalesce(assigned_admin, p_actor)
  where ticket_id = p_ticket_id;

  return public.admin_get_support_ticket_detail(p_ticket_id);
end;
$$;

-- 6. Admin Update Support Ticket RPC
create or replace function public.admin_update_support_ticket(
  p_ticket_id bigint,
  p_status text default null,
  p_priority text default null,
  p_notes text default null,
  p_actor text default null
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  ticket_record public.support_tickets%rowtype;
  audit_note text;
begin
  select * into ticket_record from public.support_tickets where ticket_id = p_ticket_id for update;
  if not found then
    raise exception 'Ticket not found' using errcode = '22023';
  end if;

  if p_status is not null and p_status not in ('open', 'in_progress', 'waiting_on_customer', 'resolved', 'closed') then
    raise exception 'Invalid ticket status' using errcode = '22023';
  end if;
  if p_priority is not null and p_priority not in ('low', 'medium', 'high', 'urgent') then
    raise exception 'Invalid ticket priority' using errcode = '22023';
  end if;

  update public.support_tickets
  set status = coalesce(p_status, status),
      priority = coalesce(p_priority, priority),
      resolution_notes = coalesce(p_notes, resolution_notes),
      assigned_admin = coalesce(p_actor, assigned_admin),
      resolved_at = case
        when p_status in ('resolved', 'closed') then coalesce(resolved_at, now())
        when p_status in ('open', 'in_progress', 'waiting_on_customer') then null
        else resolved_at
      end,
      updated_at = now()
  where ticket_id = p_ticket_id;

  -- Add system note if status changed
  if p_status is not null and p_status <> ticket_record.status then
    audit_note := 'Status changed from ' || ticket_record.status || ' to ' || p_status ||
      case when p_actor is not null then ' by ' || p_actor else '' end;
    insert into public.support_messages(
      ticket_id, sender_role, sender_name, body
    ) values (
      p_ticket_id, 'system', 'System Audit', audit_note
    );
  end if;

  return public.admin_get_support_ticket_detail(p_ticket_id);
end;
$$;

-- 7. Admin Create Support Ticket RPC
create or replace function public.admin_create_support_ticket(
  p_user_id bigint,
  p_subject text,
  p_category text,
  p_priority text default 'medium',
  p_initial_message text default null,
  p_actor text default null
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  target_user public.users%rowtype;
  new_ticket_id bigint;
  new_ticket_num text;
  detected_role text := 'general';
begin
  select * into target_user from public.users where user_id = p_user_id;
  if not found then
    raise exception 'Customer user not found' using errcode = '22023';
  end if;

  if exists (select 1 from public.farmers where farmer_user_id = p_user_id) then
    detected_role := 'farmer';
  elsif exists (select 1 from public.buyers where user_id = p_user_id) then
    detected_role := 'buyer';
  elsif exists (select 1 from public.riders r join private.auth_identities i on i.auth_user_id = r.auth_user_id where i.user_id = p_user_id) then
    detected_role := 'rider';
  end if;

  new_ticket_num := 'TCK-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));

  insert into public.support_tickets(
    ticket_number, user_id, user_role, subject, category, priority, status, assigned_admin
  ) values (
    new_ticket_num, p_user_id, detected_role, btrim(p_subject), p_category, coalesce(p_priority, 'medium'), 'open', p_actor
  ) returning ticket_id into new_ticket_id;

  if p_initial_message is not null and length(btrim(p_initial_message)) > 0 then
    insert into public.support_messages(
      ticket_id, sender_role, sender_name, body
    ) values (
      new_ticket_id, 'support', coalesce(p_actor, 'Agrisell Support'), btrim(p_initial_message)
    );
  end if;

  return public.admin_get_support_ticket_detail(new_ticket_id);
end;
$$;

-- 8. Customer-facing Support RPCs (App Side)
create or replace function public.submit_customer_support_ticket(
  p_subject text,
  p_category text,
  p_message text,
  p_priority text default 'medium'
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  current_uid uuid := auth.uid();
  resolved_user_id bigint;
  detected_role text := 'general';
  new_ticket_id bigint;
  new_ticket_num text;
  sender_display text;
begin
  select user_id into resolved_user_id
  from private.auth_identities where auth_user_id = current_uid;

  if resolved_user_id is null then
    raise exception 'You must be logged in to submit a support ticket' using errcode = '42501';
  end if;

  if exists (select 1 from public.farmers where farmer_user_id = resolved_user_id) then
    detected_role := 'farmer';
  elsif exists (select 1 from public.buyers where user_id = resolved_user_id) then
    detected_role := 'buyer';
  elsif exists (select 1 from public.riders where auth_user_id = current_uid) then
    detected_role := 'rider';
  end if;

  select coalesce(nullif(btrim(first_name || ' ' || coalesce(last_name, '')), ''), 'Customer')
  into sender_display
  from public.users where user_id = resolved_user_id;

  new_ticket_num := 'TCK-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));

  insert into public.support_tickets(
    ticket_number, user_id, user_role, subject, category, priority, status
  ) values (
    new_ticket_num, resolved_user_id, detected_role, btrim(p_subject), p_category, coalesce(p_priority, 'medium'), 'open'
  ) returning ticket_id into new_ticket_id;

  insert into public.support_messages(
    ticket_id, sender_role, sender_name, sender_user_id, body
  ) values (
    new_ticket_id, 'user', sender_display, resolved_user_id, btrim(p_message)
  );

  return jsonb_build_object(
    'ticket_id', new_ticket_id,
    'ticket_number', new_ticket_num,
    'status', 'open'
  );
end;
$$;

create or replace function public.current_user_support_tickets()
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  current_uid uuid := auth.uid();
  resolved_user_id bigint;
begin
  select user_id into resolved_user_id
  from private.auth_identities where auth_user_id = current_uid;

  return coalesce((
    select jsonb_agg(jsonb_build_object(
      'ticket_id', t.ticket_id,
      'ticket_number', t.ticket_number,
      'subject', t.subject,
      'category', t.category,
      'status', t.status,
      'priority', t.priority,
      'created_at', t.created_at,
      'updated_at', t.updated_at,
      'last_message', (
        select m.body from public.support_messages m
        where m.ticket_id = t.ticket_id
        order by m.created_at desc limit 1
      )
    ) order by t.updated_at desc)
    from public.support_tickets t
    where t.user_id = resolved_user_id
  ), '[]'::jsonb);
end;
$$;

create or replace function public.send_customer_support_message(
  p_ticket_id bigint,
  p_body text
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  current_uid uuid := auth.uid();
  resolved_user_id bigint;
  ticket_record public.support_tickets%rowtype;
  sender_display text;
  saved_msg public.support_messages%rowtype;
begin
  select user_id into resolved_user_id
  from private.auth_identities where auth_user_id = current_uid;

  select * into ticket_record from public.support_tickets where ticket_id = p_ticket_id;
  if not found or ticket_record.user_id <> resolved_user_id then
    raise exception 'Ticket access not authorized' using errcode = '42501';
  end if;

  select coalesce(nullif(btrim(first_name || ' ' || coalesce(last_name, '')), ''), 'Customer')
  into sender_display
  from public.users where user_id = resolved_user_id;

  insert into public.support_messages(
    ticket_id, sender_role, sender_name, sender_user_id, body
  ) values (
    p_ticket_id, 'user', sender_display, resolved_user_id, btrim(p_body)
  ) returning * into saved_msg;

  update public.support_tickets
  set updated_at = now(),
      status = case when status in ('resolved', 'closed') then 'open' else status end
  where ticket_id = p_ticket_id;

  return to_jsonb(saved_msg);
end;
$$;

