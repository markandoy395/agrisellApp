// Isolated PostgreSQL tests: production publication and stock functions, local accounts only.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('../../.dart-local/chat-sql/node_modules/@electric-sql/pglite');
const owner = '10000000-0000-4000-8000-000000000001';
const other = '10000000-0000-4000-8000-000000000002';
const pending = '10000000-0000-4000-8000-000000000003';
const key = '20000000-0000-4000-8000-000000000001';

async function main() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated;
    create schema auth; create schema private; create schema extensions; create schema storage;
    create table auth.users(id uuid primary key);
    insert into auth.users values('${owner}'),('${other}'),('${pending}');
    create function auth.jwt() returns jsonb language sql stable as $$
      select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
    create function auth.uid() returns uuid language sql stable as $$ select (auth.jwt()->>'sub')::uuid $$;
    create function extensions.digest(text,text) returns bytea language sql immutable as $$
      select decode(md5($1),'hex') $$;
    create function public.require_rate_limited_gateway() returns void language plpgsql as $$
      begin if current_setting('test.gateway',true) is distinct from 'valid' then
        raise insufficient_privilege; end if; end $$;
    create function private.is_admin() returns boolean language sql as $$ select false $$;
    create table public.farmers(farmer_user_id bigint primary key, auth_user_id uuid,
      account_status text, verification_status text);
    insert into public.farmers values(1,'${owner}','active','verified'),
      (2,'${other}','active','verified'),(3,'${pending}','active','pending');
    create table public.farms(farm_id bigint primary key, farmer_user_id bigint);
    insert into public.farms values(1,1),(2,2),(3,3);
    create table public.categories(category_id bigint generated by default as identity,
      farm_id bigint,category_name text,primary key(category_id,farm_id));
    create table public.commodities(commodity_id bigint generated by default as identity primary key,
      category_id bigint,farm_id bigint,commodity_name text,description text,price_per_unit numeric,
      unit_type text,available_quantity numeric,harvest_date date,production_status text,
      availability_status text,is_organic boolean,image_url text,commodity_status text,
      minimum_order_quantity numeric,grade_quality text,inventory_date_type text,
      updated_at timestamptz default now());
    create table public.commodity_inventory_lots(inventory_lot_id bigint generated always as identity,
      commodity_id bigint,date_type text not null,quantity_received numeric,quantity_remaining numeric,
      harvested_at date,sell_until date,expires_at date,lot_code text,storage_instructions text,created_by uuid);
    create table private.commodity_restock_history(commodity_id bigint,quantity_added numeric,
      previous_quantity numeric,new_quantity numeric,performed_by uuid,reason text);
    create function private.owns_farm(bigint) returns boolean language sql stable security definer as $$
      select exists(select 1 from public.farms farm join public.farmers f using(farmer_user_id)
        where farm.farm_id=$1 and f.auth_user_id=auth.uid()) $$;
    create table storage.objects(bucket_id text,name text);
    create function storage.foldername(text) returns text[] language sql immutable as $$
      select string_to_array($1,'/') $$;
    alter table public.categories enable row level security;
    alter table public.commodities enable row level security;
    alter table storage.objects enable row level security;
    create policy owner_categories on public.categories to authenticated
      using(private.owns_farm(farm_id)) with check(private.owns_farm(farm_id));
    create policy owner_commodities on public.commodities to authenticated
      using(private.owns_farm(farm_id)) with check(private.owns_farm(farm_id));
    create policy owner_storage on storage.objects to authenticated
      using(split_part(name,'/',1)=auth.uid()::text) with check(split_part(name,'/',1)=auth.uid()::text);
    grant usage on schema public,auth,private,extensions,storage to authenticated,anon;
    grant select,insert,update on public.categories,public.commodities,storage.objects to authenticated;
    grant usage on all sequences in schema public to authenticated;
  `);
  const concurrency = fs.readFileSync('supabase/migrations/20261016110000_concurrent_operations.sql','utf8');
  await db.exec(concurrency.slice(0, concurrency.indexOf('create function public.send_marketplace_message_once')) + '\ncommit;');
  const inventory = fs.readFileSync('supabase/migrations/20260828120000_add_batch_inventory_freshness.sql','utf8');
  await db.exec(inventory.slice(inventory.indexOf('create or replace function private.add_current_farmer_inventory_lot('),
    inventory.indexOf('create or replace function public.restock_current_farmer_inventory_lot(')));
  await db.exec(fs.readFileSync('supabase/migrations/20261020100000_secure_atomic_farmer_publication.sql','utf8'));
  const today = (await db.query('select current_date::text today, (current_date+7)::text until')).rows[0];
  const lot = { date_type:'fresh_produce',harvested_at:today.today,sell_until:today.until };
  const product = { farm_id:1,commodity_name:"Tomato_%_' ; --",category_name:"Vegetables_%_'",
    description:'Fresh produce',price_per_unit:50,unit_type:'kg',available_quantity:10,
    minimum_order_quantity:1,harvest_date:today.today,production_status:'harvested',
    availability_status:'ready_now',is_organic:true,
    image_url:`https://example.test/storage/v1/object/public/farmer-media/${owner}/commodities/${key}-${'a'.repeat(64)}.jpg` };
  const publish = (p=product,l=lot,k=key) => db.query(
    'select public.publish_current_farmer_product($1,$2,$3) result',[k,p,l]);
  const denied = (action,code) => assert.rejects(action,e=>e.code===code);
  async function session(id=owner,extra={}) {
    await db.exec('reset role');
    await db.query("select set_config('request.jwt.claims',$1,false),set_config('test.gateway','valid',false)",
      [JSON.stringify({sub:id,is_anonymous:false,exp:4102444800,...extra})]);
    await db.exec('set role authenticated');
  }
  async function counts() {
    await db.exec('reset role');
    return (await db.query(`select (select count(*) from public.commodities)::int products,
      (select count(*) from public.categories)::int categories,
      (select count(*) from public.commodity_inventory_lots)::int lots,
      (select count(*) from private.application_operation_receipts)::int receipts`)).rows[0];
  }
  await session();
  await denied(()=>publish(product,{...lot,sell_until:'2000-01-01'}),'22023');
  assert.deepEqual(await counts(),{products:0,categories:0,lots:0,receipts:0});
  await session();
  const saved = (await publish()).rows[0].result;
  assert.equal(saved.available_quantity,10);
  assert.equal(saved.commodity_name,product.commodity_name);
  assert.deepEqual((await publish()).rows[0].result,saved);
  await denied(()=>publish({...product,available_quantity:20}),'22023');
  await denied(()=>publish({...product,farm_id:2}),'42501');
  assert.deepEqual(await counts(),{products:1,categories:1,lots:1,receipts:1});
  await session(other);
  await denied(()=>publish(),'42501');
  await session(pending);
  await denied(()=>publish({...product,farm_id:3}),'42501');
  await denied(()=>db.query("insert into public.categories(farm_id,category_name) values(3,'Blocked')"),'42501');
  await denied(()=>db.query("insert into public.commodities(farm_id,commodity_name) values(3,'Blocked')"),'42501');
  await denied(()=>db.query('insert into storage.objects values($1,$2)',
    ['farmer-media',`${pending}/commodities/file.jpg`]),'42501');
  await db.query('insert into storage.objects values($1,$2)',['farmer-media',`${pending}/profile.jpg`]);
  await denied(()=>db.query('select private.add_current_farmer_inventory_lot($1,1,$2,current_date,current_date+7,null,null,null,null)',
    [saved.commodity_id,'fresh_produce']),'42501');
  await session(owner,{is_anonymous:true}); await denied(()=>publish(),'PT401');
  await session(owner,{exp:1}); await denied(()=>publish(),'PT401');
  await session(null); await denied(()=>publish(),'PT401');
  await session(); await db.exec("set test.gateway='invalid'"); await denied(()=>publish(),'42501');
  await session(); await db.exec('set role anon'); await denied(()=>publish(),'42501');
  await session(); await denied(()=>db.query('select * from private.application_operation_receipts'),'42501');
  // Removing approval prevents existing owners from restocking through the definer helper.
  await db.exec("reset role; update public.farmers set verification_status='pending' where farmer_user_id=1");
  await session();
  await denied(()=>db.query('select private.add_current_farmer_inventory_lot($1,1,$2,current_date,current_date+7,null,null,null,null)',
    [saved.commodity_id,'fresh_produce']),'42501');
  assert.deepEqual(await counts(),{products:1,categories:1,lots:1,receipts:1});
  await db.close();
  console.log('PASS: atomic rollback, same-key retry, ownership, approval, storage, sessions, gateway, literal input');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
