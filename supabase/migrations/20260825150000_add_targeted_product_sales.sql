begin;

-- A buyer is "new" for promotions for 30 days after registration and until
-- they have placed an order.  This is intentionally evaluated from the
-- account and order records, never from a client-provided flag.
create table if not exists public.product_sales (
  sale_id bigint generated by default as identity primary key,
  name text not null,
  discount_type text not null,
  discount_value numeric(14,2) not null,
  target_user_group text not null default 'all_users',
  starts_at timestamptz,
  ends_at timestamptz,
  is_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint product_sales_discount_type_check
    check (discount_type in ('sale_price', 'percentage', 'amount')),
  constraint product_sales_target_user_group_check
    check (target_user_group in ('all_users', 'new_users_only')),
  constraint product_sales_discount_value_check check (discount_value > 0),
  constraint product_sales_dates_check check (ends_at is null or starts_at is null or ends_at > starts_at)
);

create table if not exists public.product_sale_items (
  sale_id bigint not null references public.product_sales(sale_id) on delete cascade,
  commodity_id bigint not null references public.commodities(commodity_id) on delete cascade,
  primary key (sale_id, commodity_id)
);

create index if not exists product_sale_items_commodity_id_idx
  on public.product_sale_items (commodity_id);
create index if not exists product_sales_active_window_idx
  on public.product_sales (is_enabled, starts_at, ends_at);

alter table public.product_sales enable row level security;
alter table public.product_sale_items enable row level security;
revoke all on public.product_sales, public.product_sale_items from anon, authenticated;

create or replace function private.is_new_buyer_sale_eligible(
  target_buyer_id bigint
) returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1
    from public.buyers as buyer
    join public.users as account on account.user_id = buyer.user_id
    where buyer.buyer_user_id = target_buyer_id
      and account.created_at >= transaction_timestamp() - interval '30 days'
      and not exists (
        select 1
        from public.orders as order_record
        join public.cart_items as cart_item
          on cart_item.cart_item_id = order_record.cart_item_id
        join public.carts as cart on cart.cart_id = cart_item.cart_id
        where cart.buyer_user_id = target_buyer_id
          -- Orders created during this checkout retain the eligibility that
          -- existed when the checkout transaction began.
          and coalesce(order_record.order_date, order_record.created_at)
              < transaction_timestamp()
      )
  )
$$;

create or replace function private.effective_commodity_price(
  target_commodity_id bigint,
  target_buyer_id bigint default private.current_buyer_user_id()
) returns numeric language sql stable security definer set search_path = '' as $$
  with base as (
    select commodity.price_per_unit as original_price
    from public.commodities as commodity
    where commodity.commodity_id = target_commodity_id
  ), candidates as (
    select case sale.discount_type
      when 'sale_price' then sale.discount_value
      when 'percentage' then base.original_price * (1 - sale.discount_value / 100)
      when 'amount' then base.original_price - sale.discount_value
    end as price
    from base
    join public.product_sale_items as item
      on item.commodity_id = target_commodity_id
    join public.product_sales as sale on sale.sale_id = item.sale_id
    where sale.is_enabled
      and (sale.starts_at is null or sale.starts_at <= transaction_timestamp())
      and (sale.ends_at is null or sale.ends_at > transaction_timestamp())
      and (sale.target_user_group = 'all_users'
        or (sale.target_user_group = 'new_users_only'
          and target_buyer_id is not null
          and private.is_new_buyer_sale_eligible(target_buyer_id)))
  )
  select coalesce(
    (select round(min(price), 2) from candidates
      where price > 0 and price < (select original_price from base)),
    (select original_price from base)
  )
$$;

create or replace function private.validate_product_sale_item()
returns trigger language plpgsql security definer set search_path = '' as $$
declare base_price numeric;
declare configured_price numeric;
begin
  select price_per_unit into base_price
  from public.commodities where commodity_id = new.commodity_id;
  select case discount_type
    when 'sale_price' then discount_value
    when 'percentage' then base_price * (1 - discount_value / 100)
    else base_price - discount_value end
  into configured_price
  from public.product_sales where sale_id = new.sale_id;
  if base_price is null or configured_price is null
     or configured_price <= 0 or configured_price >= base_price then
    raise exception 'A sale price must be greater than zero and lower than the original product price'
      using errcode = '22023';
  end if;
  return new;
end;
$$;
drop trigger if exists product_sale_items_validate_price on public.product_sale_items;
create trigger product_sale_items_validate_price
before insert or update on public.product_sale_items
for each row execute function private.validate_product_sale_item();

-- The price supplied by the app is never trusted.  Every cart snapshot and
-- every resulting order/payment receives the effective server price instead.
create or replace function private.set_cart_item_effective_price()
returns trigger language plpgsql security definer set search_path = '' as $$
declare target_buyer_id bigint;
begin
  select buyer_user_id into target_buyer_id
  from public.carts where cart_id = new.cart_id;
  new.price_at_time := private.effective_commodity_price(
    new.commodity_id, target_buyer_id
  );
  return new;
end;
$$;
drop trigger if exists cart_items_set_effective_price on public.cart_items;
create trigger cart_items_set_effective_price
before insert or update of commodity_id, price_at_time on public.cart_items
for each row execute function private.set_cart_item_effective_price();

create or replace function private.set_order_effective_total()
returns trigger language plpgsql security definer set search_path = '' as $$
declare unit_price numeric;
declare quantity numeric;
begin
  select cart_item.price_at_time, cart_item.quantity into unit_price, quantity
  from public.cart_items as cart_item where cart_item.cart_item_id = new.cart_item_id;
  new.total_amount := round(unit_price * quantity, 2);
  return new;
end;
$$;
drop trigger if exists orders_set_effective_total on public.orders;
create trigger orders_set_effective_total
before insert on public.orders for each row execute function private.set_order_effective_total();

create or replace function private.set_order_item_effective_price()
returns trigger language plpgsql security definer set search_path = '' as $$
declare unit_price numeric;
begin
  select cart_item.price_at_time into unit_price
  from public.orders as order_record
  join public.cart_items as cart_item on cart_item.cart_item_id = order_record.cart_item_id
  where order_record.order_id = new.order_id;
  new.unit_price := unit_price;
  new.total_price := round(unit_price * new.quantity, 2);
  return new;
end;
$$;
drop trigger if exists order_items_set_effective_price on public.order_items;
create trigger order_items_set_effective_price
before insert on public.order_items for each row execute function private.set_order_item_effective_price();

create or replace function private.set_payment_effective_amount()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  select total_amount into new.amount from public.orders where order_id = new.order_id;
  return new;
end;
$$;
drop trigger if exists payments_set_effective_amount on public.payments;
create trigger payments_set_effective_amount
before insert on public.payments for each row execute function private.set_payment_effective_amount();

-- Keep the pre-existing checkout workflow intact.  It validates a rewritten
-- server-side copy of the submitted price; the cart/order triggers above then
-- persist the sale price.  A manipulated client price is therefore ignored.
alter function private.sync_current_buyer_orders(jsonb)
  rename to sync_current_buyer_orders_base_price;

create or replace function private.sync_current_buyer_orders(order_payload jsonb)
returns void language plpgsql security definer set search_path = '' as $$
declare target_buyer_id bigint := private.current_buyer_user_id();
declare trusted_payload jsonb;
begin
  if target_buyer_id is null then
    raise exception 'An authenticated buyer account is required' using errcode = '42501';
  end if;
  if jsonb_typeof(order_payload) <> 'array' then
    raise exception 'Order payload must be an array' using errcode = '22023';
  end if;
  select jsonb_agg(
    order_record.value - 'items' || jsonb_build_object('items', coalesce(items, '[]'::jsonb))
  ) into trusted_payload
  from jsonb_array_elements(order_payload) as order_record
  cross join lateral (
    select jsonb_agg(item.value - 'pricePerKg' || jsonb_build_object(
      'pricePerKg', commodity.price_per_unit
    )) as items
    from jsonb_array_elements(case when jsonb_typeof(order_record.value -> 'items') = 'array'
      then order_record.value -> 'items' else '[]'::jsonb end) as item
    join public.commodities as commodity
      on commodity.commodity_id = nullif(item.value ->> 'productId', '')::bigint
  ) as rebuilt;
  perform private.sync_current_buyer_orders_base_price(coalesce(trusted_payload, '[]'::jsonb));
end;
$$;

create or replace function public.marketplace_products(p_farm_id bigint default null)
returns table (
  commodity_id bigint, commodity_name text, description text, price_per_unit numeric,
  effective_price numeric, unit_type text, image_url text, harvest_date date,
  available_quantity numeric, farm_id bigint, commodity_status text,
  availability_status text, production_status text, rating numeric, category_name text
) language sql stable security definer set search_path = '' as $$
  select commodity.commodity_id, commodity.commodity_name, commodity.description,
    commodity.price_per_unit,
    private.effective_commodity_price(commodity.commodity_id, private.current_buyer_user_id()),
    commodity.unit_type, commodity.image_url, commodity.harvest_date,
    commodity.available_quantity, commodity.farm_id, commodity.commodity_status,
    commodity.availability_status, commodity.production_status, commodity.rating,
    category.category_name
  from public.commodities as commodity
  left join public.categories as category
    on category.category_id = commodity.category_id and category.farm_id = commodity.farm_id
  where lower(coalesce(commodity.commodity_status, '')) = 'available'
    and coalesce(commodity.available_quantity, 0) > 0
    and commodity.availability_status <> 'not_accepting_orders'
    and (p_farm_id is null or commodity.farm_id = p_farm_id)
  order by commodity.created_at desc
$$;

revoke all on function private.is_new_buyer_sale_eligible(bigint),
  private.effective_commodity_price(bigint, bigint),
  private.validate_product_sale_item(), private.set_cart_item_effective_price(),
  private.set_order_effective_total(), private.set_order_item_effective_price(),
  private.set_payment_effective_amount(), private.sync_current_buyer_orders_base_price(jsonb),
  private.sync_current_buyer_orders(jsonb) from public, anon;
grant execute on function private.sync_current_buyer_orders(jsonb) to authenticated;
revoke all on function public.marketplace_products(bigint) from public, anon;
grant execute on function public.marketplace_products(bigint) to authenticated;

notify pgrst, 'reload schema';
commit;
