begin;

create table if not exists public.admin_broadcasts (
  broadcast_id bigint generated by default as identity primary key,
  title text not null,
  message text not null,
  target_segment text not null default 'all',
  notification_type text not null default 'announcement',
  destination text not null default 'none',
  recipient_count integer not null default 0,
  sent_by_email text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_broadcasts_created_at_idx
  on public.admin_broadcasts (created_at desc);

create index if not exists admin_broadcasts_target_segment_idx
  on public.admin_broadcasts (target_segment, created_at desc);

alter table public.admin_broadcasts enable row level security;

drop policy if exists admin_broadcasts_select on public.admin_broadcasts;
create policy admin_broadcasts_select on public.admin_broadcasts
  for select to authenticated
  using (private.is_admin());

drop policy if exists admin_broadcasts_insert on public.admin_broadcasts;
create policy admin_broadcasts_insert on public.admin_broadcasts
  for insert to authenticated
  with check (private.is_admin());

commit;
