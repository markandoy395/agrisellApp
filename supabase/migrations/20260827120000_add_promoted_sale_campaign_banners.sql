begin;

-- A discount changes prices. Promotion on the Buyer home is an explicit,
-- campaign-level choice and never follows automatically from a sale item.
alter table public.product_sales
  add column if not exists promote_on_home boolean not null default false;

create index if not exists product_sales_promoted_window_idx
  on public.product_sales (promote_on_home, is_enabled, starts_at, ends_at);

-- Manual editorial banners remain separate from automatic sale-campaign
-- banners. They can be managed independently without creating product sales.
create table if not exists public.manual_home_banners (
  banner_id bigint generated by default as identity primary key,
  prefix text not null default '',
  highlight text not null default '',
  subtitle text not null default '',
  title text not null,
  image_url text,
  target_user_group text not null default 'all_users',
  starts_at timestamptz,
  ends_at timestamptz,
  is_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint manual_home_banners_target_group_check
    check (target_user_group in ('all_users', 'new_users_only')),
  constraint manual_home_banners_dates_check
    check (ends_at is null or starts_at is null or ends_at > starts_at)
);

alter table public.manual_home_banners enable row level security;
revoke all on public.manual_home_banners from anon, authenticated;

-- Legacy clients continue to receive one row per explicitly promoted sale.
-- Grouping is by sale_id, so editing a campaign updates the same banner rather
-- than inserting a duplicate.
create or replace function public.marketplace_promotion_banners()
returns table (
  sale_id bigint, sale_name text, discount_type text, discount_value numeric,
  commodity_name text, image_url text, ends_at timestamptz
) language sql stable security definer set search_path = '' as $$
  select
    sale.sale_id,
    sale.name,
    sale.discount_type,
    sale.discount_value,
    case
      when products.product_count = 1 then products.featured_name
      else products.featured_name || ' + ' ||
        (products.product_count - 1)::text || ' more'
    end,
    products.featured_image_url,
    sale.ends_at
  from public.product_sales as sale
  join lateral (
    select
      count(*) as product_count,
      (array_agg(
        commodity.commodity_name order by item.commodity_id
      ))[1] as featured_name,
      (array_agg(
        commodity.image_url order by item.commodity_id
      ) filter (where commodity.image_url is not null))[1]
        as featured_image_url
    from public.product_sale_items as item
    join public.commodities as commodity
      on commodity.commodity_id = item.commodity_id
    where item.sale_id = sale.sale_id
  ) as products on products.product_count > 1
  where sale.promote_on_home
    and sale.is_enabled
    and (sale.starts_at is null or sale.starts_at <= transaction_timestamp())
    and (sale.ends_at is null or sale.ends_at > transaction_timestamp())
    and (
      sale.target_user_group = 'all_users'
      or (
        sale.target_user_group = 'new_users_only'
        and private.is_new_buyer_sale_eligible(
          private.current_buyer_user_id()
        )
      )
    )
  order by sale.starts_at nulls first, sale.created_at desc
$$;

create or replace function public.marketplace_home_banners()
returns table (
  banner_id text,
  banner_source text,
  campaign_sale_id bigint,
  prefix text,
  highlight text,
  subtitle text,
  title text,
  image_url text,
  ends_at timestamptz
) language sql stable security definer set search_path = '' as $$
  select
    banner.banner_id,
    banner.banner_source,
    banner.campaign_sale_id,
    banner.prefix,
    banner.highlight,
    banner.subtitle,
    banner.title,
    banner.image_url,
    banner.ends_at
  from (
    select
      'campaign:' || promotion.sale_id::text as banner_id,
      'campaign'::text as banner_source,
      promotion.sale_id as campaign_sale_id,
      'Save '::text as prefix,
      case promotion.discount_type
        when 'percentage' then
          to_char(promotion.discount_value, 'FM999999990.##') || '%'
        when 'amount' then
          chr(8369) || to_char(promotion.discount_value, 'FM999999990.##')
        else 'Sale'
      end as highlight,
      promotion.sale_name as subtitle,
      upper(promotion.commodity_name) as title,
      promotion.image_url,
      promotion.ends_at,
      sale.created_at as sort_at
    from public.marketplace_promotion_banners() as promotion
    join public.product_sales as sale on sale.sale_id = promotion.sale_id

    union all

    select
      'manual:' || manual.banner_id::text,
      'manual'::text,
      null::bigint,
      manual.prefix,
      manual.highlight,
      manual.subtitle,
      manual.title,
      manual.image_url,
      manual.ends_at,
      manual.created_at
    from public.manual_home_banners as manual
    where manual.is_enabled
      and (manual.starts_at is null
        or manual.starts_at <= transaction_timestamp())
      and (manual.ends_at is null
        or manual.ends_at > transaction_timestamp())
      and (
        manual.target_user_group = 'all_users'
        or (
          manual.target_user_group = 'new_users_only'
          and private.is_new_buyer_sale_eligible(
            private.current_buyer_user_id()
          )
        )
      )
  ) as banner
  order by banner.sort_at desc, banner.banner_id
$$;

create or replace function public.marketplace_sale_campaign_products(
  p_sale_id bigint
) returns table (
  commodity_id bigint, commodity_name text, description text,
  price_per_unit numeric, effective_price numeric, unit_type text,
  image_url text, harvest_date date, available_quantity numeric,
  farm_id bigint, commodity_status text, availability_status text,
  production_status text, rating numeric, category_name text
) language sql stable security definer set search_path = '' as $$
  select product.*
  from public.marketplace_products(null) as product
  join public.product_sale_items as item
    on item.commodity_id = product.commodity_id
  join public.product_sales as sale on sale.sale_id = item.sale_id
  where sale.sale_id = p_sale_id
    and sale.promote_on_home
    and sale.is_enabled
    and 1 < (
      select count(*)
      from public.product_sale_items as campaign_item
      where campaign_item.sale_id = sale.sale_id
    )
    and (sale.starts_at is null or sale.starts_at <= transaction_timestamp())
    and (sale.ends_at is null or sale.ends_at > transaction_timestamp())
    and (
      sale.target_user_group = 'all_users'
      or (
        sale.target_user_group = 'new_users_only'
        and private.is_new_buyer_sale_eligible(
          private.current_buyer_user_id()
        )
      )
    )
  order by product.commodity_name, product.commodity_id
$$;

revoke all on function public.marketplace_promotion_banners(),
  public.marketplace_home_banners(),
  public.marketplace_sale_campaign_products(bigint)
  from public, anon, authenticated;
grant execute on function public.marketplace_promotion_banners(),
  public.marketplace_home_banners(),
  public.marketplace_sale_campaign_products(bigint)
  to anon, authenticated;

notify pgrst, 'reload schema';
commit;
