-- Farmer Review Reports & Moderation Appeals Migration
-- Allows farmers to report malicious/abusive reviews and appeal administrative moderation penalties.
begin;

-- 1. Farmer Review Appeals & Reports Table
create table if not exists public.farmer_review_appeals (
  appeal_id bigint generated by default as identity primary key,
  review_id bigint not null references public.reviews(review_id) on delete cascade,
  farmer_user_id bigint not null references public.users(user_id) on delete cascade,
  action_type text not null check (action_type in ('report', 'appeal')),
  reason text not null check (char_length(btrim(reason)) between 2 and 100),
  details text check (details is null or char_length(details) <= 1000),
  status text not null default 'open' check (status in ('open', 'under_review', 'resolved', 'dismissed')),
  admin_notes text,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

-- Indexes
create index if not exists farmer_review_appeals_review_idx
  on public.farmer_review_appeals(review_id, created_at desc);
create index if not exists farmer_review_appeals_farmer_idx
  on public.farmer_review_appeals(farmer_user_id, created_at desc);
create index if not exists farmer_review_appeals_status_idx
  on public.farmer_review_appeals(status, created_at desc);

-- 2. Row Level Security
alter table public.farmer_review_appeals enable row level security;

create policy farmer_review_appeals_farmer_select on public.farmer_review_appeals
  for select to authenticated
  using (
    farmer_user_id = coalesce(
      private.current_farmer_user_id(),
      private.current_authenticated_farmer_user_id()
    )
    or private.is_admin()
  );

create policy farmer_review_appeals_farmer_insert on public.farmer_review_appeals
  for insert to authenticated
  with check (
    farmer_user_id = coalesce(
      private.current_farmer_user_id(),
      private.current_authenticated_farmer_user_id()
    )
    or private.is_admin()
  );

-- 3. Farmer Submit Review Report or Appeal RPC
create or replace function public.submit_farmer_review_report_or_appeal(
  p_review_id bigint,
  p_action_type text,
  p_reason text,
  p_details text default null
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  current_farmer bigint;
  target_review public.reviews%rowtype;
  normalized_action text := lower(btrim(coalesce(p_action_type, '')));
  normalized_reason text := btrim(coalesce(p_reason, ''));
  normalized_details text := nullif(btrim(coalesce(p_details, '')), '');
  saved_appeal public.farmer_review_appeals%rowtype;
  mapped_abuse_flag text := 'other';
begin
  select coalesce(
    private.current_farmer_user_id(),
    private.current_authenticated_farmer_user_id()
  ) into current_farmer;

  if current_farmer is null then
    raise exception 'Unauthorized: Only registered farmers can report reviews or appeal moderation' using errcode = '42501';
  end if;

  if normalized_action not in ('report', 'appeal') then
    raise exception 'Invalid action type: must be report or appeal' using errcode = '22023';
  end if;

  if char_length(normalized_reason) < 2 or char_length(normalized_reason) > 100 then
    raise exception 'Reason must be between 2 and 100 characters' using errcode = '22023';
  end if;

  if normalized_details is not null and char_length(normalized_details) > 1000 then
    raise exception 'Details cannot exceed 1000 characters' using errcode = '22023';
  end if;

  select * into target_review
  from public.reviews
  where review_id = p_review_id and farmer_user_id = current_farmer;

  if not found then
    raise exception 'Review not found or not owned by current farmer' using errcode = 'P0002';
  end if;

  -- Map reason keyword to existing abuse flags if possible
  if position('spam' in lower(normalized_reason)) > 0 then
    mapped_abuse_flag := 'spam';
  elsif position('harass' in lower(normalized_reason)) > 0 then
    mapped_abuse_flag := 'harassment';
  elsif position('hate' in lower(normalized_reason)) > 0 then
    mapped_abuse_flag := 'hate_speech';
  elsif position('profan' in lower(normalized_reason)) > 0 then
    mapped_abuse_flag := 'profanity';
  elsif position('scam' in lower(normalized_reason)) > 0 or position('fake' in lower(normalized_reason)) > 0 then
    mapped_abuse_flag := 'scam';
  elsif position('personal' in lower(normalized_reason)) > 0 or position('privacy' in lower(normalized_reason)) > 0 then
    mapped_abuse_flag := 'personal_information';
  else
    mapped_abuse_flag := 'other';
  end if;

  insert into public.farmer_review_appeals(
    review_id, farmer_user_id, action_type, reason, details, status
  ) values (
    p_review_id, current_farmer, normalized_action, normalized_reason, normalized_details, 'open'
  ) returning * into saved_appeal;

  -- Upsert into admin_review_moderation to mark report_status as open
  insert into public.admin_review_moderation (
    review_type, review_id, report_status, last_note, updated_by_email, updated_at
  ) values (
    'farmer',
    p_review_id::text,
    'open',
    (case when normalized_action = 'appeal' then 'Farmer Appeal: [' else 'Farmer Report: [' end)
      || normalized_reason || ']' || coalesce(' - ' || normalized_details, ''),
    'farmer:' || current_farmer::text,
    now()
  )
  on conflict (review_type, review_id) do update
  set report_status = 'open',
      last_note = (case when normalized_action = 'appeal' then 'Farmer Appeal: [' else 'Farmer Report: [' end)
        || normalized_reason || ']' || coalesce(' - ' || normalized_details, ''),
      updated_by_email = 'farmer:' || current_farmer::text,
      updated_at = now();

  -- Record audit event in admin_review_moderation_events
  insert into public.admin_review_moderation_events (
    review_type, review_id, action, abuse_flag, note, created_by_email, created_at
  ) values (
    'farmer',
    p_review_id::text,
    'report_reopened',
    mapped_abuse_flag,
    (case when normalized_action = 'appeal' then 'Farmer appeal: [' else 'Farmer report: [' end)
      || normalized_reason || ']' || coalesce(' - ' || normalized_details, ''),
    'farmer:' || current_farmer::text,
    now()
  );

  return jsonb_build_object(
    'appeal_id', saved_appeal.appeal_id,
    'review_id', saved_appeal.review_id,
    'action_type', saved_appeal.action_type,
    'reason', saved_appeal.reason,
    'details', saved_appeal.details,
    'status', saved_appeal.status,
    'created_at', saved_appeal.created_at
  );
end;
$$;

revoke all on function public.submit_farmer_review_report_or_appeal(bigint, text, text, text) from public, anon;
grant execute on function public.submit_farmer_review_report_or_appeal(bigint, text, text, text) to authenticated;

notify pgrst, 'reload schema';
commit;
