begin;

-- Farmer verification is an administrator decision. Do not let an
-- authenticated farmer set either account status field on their own profile.
revoke update (verification_status, account_status) on public.farmers from authenticated;

-- Registration and profile images remain available to pending farmers, but a
-- commodity image may only be uploaded after the farmer has been approved.
drop policy if exists farmer_media_insert on storage.objects;
drop policy if exists farmer_media_update on storage.objects;
create policy farmer_media_insert on storage.objects for insert to authenticated
  with check (
    bucket_id = 'farmer-media'
    and (storage.foldername(name))[1] = (select auth.uid())::text
    and (
      (storage.foldername(name))[2] is distinct from 'commodities'
      or exists (
        select 1 from public.farmers farmer
        where farmer.auth_user_id = (select auth.uid())
          and lower(farmer.verification_status) = 'verified'
      )
    )
  );
create policy farmer_media_update on storage.objects for update to authenticated
  using (
    bucket_id = 'farmer-media'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  ) with check (
    bucket_id = 'farmer-media'
    and (storage.foldername(name))[1] = (select auth.uid())::text
    and (
      (storage.foldername(name))[2] is distinct from 'commodities'
      or exists (
        select 1 from public.farmers farmer
        where farmer.auth_user_id = (select auth.uid())
          and lower(farmer.verification_status) = 'verified'
      )
    )
  );

create table if not exists public.notifications (
  notification_id bigint generated by default as identity primary key,
  recipient_auth_user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  description text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create index if not exists notifications_recipient_created_at_idx
  on public.notifications (recipient_auth_user_id, created_at desc);

alter table public.notifications enable row level security;

drop policy if exists notifications_recipient_read on public.notifications;
create policy notifications_recipient_read on public.notifications
  for select to authenticated
  using (recipient_auth_user_id = (select auth.uid()));

drop policy if exists notifications_recipient_mark_read on public.notifications;
create policy notifications_recipient_mark_read on public.notifications
  for update to authenticated
  using (recipient_auth_user_id = (select auth.uid()))
  with check (recipient_auth_user_id = (select auth.uid()));

grant select, update (read_at) on public.notifications to authenticated;

-- Give farmers who were approved before this migration the same approval
-- update that newly approved farmers receive from the trigger below.
insert into public.notifications (
  recipient_auth_user_id, title, description
)
select
  farmer.auth_user_id,
  'Farmer account approved',
  'Your farmer account has been approved. You can now add products.'
from public.farmers farmer
where lower(farmer.verification_status) = 'verified'
  and not exists (
    select 1 from public.notifications notification
    where notification.recipient_auth_user_id = farmer.auth_user_id
      and notification.title = 'Farmer account approved'
  );

create or replace function private.notify_farmer_verification_change()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if lower(new.verification_status) is not distinct from
     lower(old.verification_status) then
    return new;
  end if;

  insert into public.notifications (
    recipient_auth_user_id, title, description
  ) values (
    new.auth_user_id,
    case lower(new.verification_status)
      when 'verified' then 'Farmer account approved'
      when 'rejected' then 'Farmer account update'
      when 'suspended' then 'Farmer account suspended'
      else 'Farmer verification updated'
    end,
    case lower(new.verification_status)
      when 'verified' then 'Your farmer account has been approved. You can now add products.'
      when 'rejected' then 'Your farmer verification was not approved. Please review your account details.'
      when 'suspended' then 'Your farmer account has been suspended. Product posting is unavailable.'
      else 'Your farmer verification status has been updated.'
    end
  );
  return new;
end;
$$;

drop trigger if exists farmer_verification_notification on public.farmers;
create trigger farmer_verification_notification
after update of verification_status on public.farmers
for each row execute function private.notify_farmer_verification_change();

commit;
